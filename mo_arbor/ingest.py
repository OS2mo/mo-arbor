"""Ingest: turn the newest dump of each code system into unit events."""

import asyncio

import structlog
from fastapi import APIRouter
from fastapi import HTTPException
from fastramqpi.depends import Sessionmaker
from pydantic import BaseModel
from sqlalchemy.dialects.postgresql import insert
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy.ext.asyncio import async_sessionmaker

from mo_arbor import depends
from mo_arbor.autogenerated_graphql_client import EventSendInput
from mo_arbor.autogenerated_graphql_client import GraphQLClient
from mo_arbor.code_system_file import InvalidFile
from mo_arbor.code_system_file import Unit
from mo_arbor.config import CodeSystem
from mo_arbor.database import LastIngested
from mo_arbor.diff import Diff
from mo_arbor.diff import diff
from mo_arbor.dumps import DumpNotFound
from mo_arbor.dumps import DumpStore

router = APIRouter()
logger = structlog.stdlib.get_logger()


class Ingested(BaseModel):
    file_name: str
    changes: Diff


class TooManyTerminations(Exception):
    pass


async def send_events(
    mo: GraphQLClient, code_system: CodeSystem, user_keys: set[str]
) -> None:
    async with asyncio.TaskGroup() as tg:
        for user_key in user_keys:
            tg.create_task(
                mo.send_event(
                    input=EventSendInput(
                        namespace=code_system.name,
                        routing_key="org_unit",
                        subject=user_key,
                    )
                )
            )


async def ingest_code_system(
    code_system: CodeSystem,
    mo: GraphQLClient,
    store: DumpStore,
    sessionmaker: async_sessionmaker[AsyncSession],
    dry_run: bool,
    force: bool,
) -> Ingested | None:
    log = logger.bind(code_system=code_system.name)
    file_name = await store.newest_file_name(mo)

    async with sessionmaker() as session:
        last_ingested = await session.get(LastIngested, code_system.name)
    if last_ingested is not None and last_ingested.file_name == file_name:
        return None

    dump = await store.load(mo, file_name)
    # Without a last ingested dump, an event is sent for every unit in the
    # newest dump
    previous_units: dict[str, Unit] = {}
    if last_ingested is not None:
        # Without it, the units removed since cannot be found
        previous = await store.load(mo, last_ingested.file_name)
        previous_units = previous.units

    changes = diff(previous_units, dump.units)
    ingested = Ingested(file_name=file_name, changes=changes)

    if len(changes.removed) > code_system.max_terminations and not force:
        raise TooManyTerminations(
            f"{file_name} has more than {code_system.max_terminations} terminations"
        )

    log.info(
        "Ingesting dump",
        file_name=file_name,
        added=len(changes.added),
        changed=len(changes.changed),
        removed=len(changes.removed),
        dry_run=dry_run,
    )
    if dry_run:
        return ingested
    # Events are sent before the dump is recorded, so if we crash in between,
    # the next ingest sends them again rather than losing them. An event sent
    # twice is harmless, as the handler reads the newest dump either way.
    await send_events(
        mo, code_system, changes.added | changes.changed | changes.removed
    )
    async with sessionmaker() as session, session.begin():
        await session.execute(
            insert(LastIngested)
            .values(code_system=code_system.name, file_name=file_name)
            .on_conflict_do_update(
                index_elements=[LastIngested.code_system],
                set_={"file_name": file_name},
            )
        )
    return ingested


@router.post("/ingest")
async def ingest(
    settings: depends.Settings,
    mo: depends.GraphQLClient,
    dump_stores: depends.DumpStores,
    sessionmaker: Sessionmaker,
    code_system: str | None = None,
    dry_run: bool = False,
    force: bool = False,
) -> dict[str, Ingested | None]:
    """Send a unit event for each unit that changed since the last ingest.

    Ingests every code system, or only the one named by `code_system`. The
    newest dump of a code system is compared to its last ingested one. Dumps
    in between are skipped, as the event handler always reads the newest dump.

    A code system without dumps is logged as an error, as its `file_pattern`
    may be wrong.

    Nothing is ingested for a code system whose newest dump is invalid, whose
    last ingested dump is gone or invalid, or whose newest dump removes more
    than its `max_terminations` units unless `force` is set. These are logged
    as errors, and the request fails after the other code systems are
    ingested.

    With `dry_run`, returns what would be ingested without sending events or
    recording anything.
    """
    if code_system is None:
        code_systems = settings.code_systems
    else:
        c = settings.get_code_system(code_system)
        if c is None:
            raise HTTPException(status_code=404, detail="Unknown code system")
        code_systems = [c]

    results: dict[str, Ingested | None] = {}
    failed = []
    for c in code_systems:
        try:
            results[c.name] = await ingest_code_system(
                c, mo, dump_stores[c.name], sessionmaker, dry_run=dry_run, force=force
            )
        except (DumpNotFound, InvalidFile, TooManyTerminations) as e:
            logger.error("Not ingested", code_system=c.name, error=str(e))
            failed.append(c.name)
    if failed:
        raise HTTPException(
            status_code=500, detail=f"Not ingested: {', '.join(failed)}"
        )
    return results
