"""Ingest: turn the newest dump of each code system into unit events."""

import asyncio

import structlog
from fastapi import APIRouter
from fastapi import HTTPException
from fastramqpi.depends import Sessionmaker
from pydantic import BaseModel
from sqlalchemy.dialects.postgresql import insert
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy.ext.asyncio import async_sessionmaker

from mo_arbor import depends
from mo_arbor.autogenerated_graphql_client import EventSendInput
from mo_arbor.autogenerated_graphql_client import GraphQLClient
from mo_arbor.code_system_file import InvalidFile
from mo_arbor.code_system_file import Unit
from mo_arbor.config import CodeSystem
from mo_arbor.database import LastApplied
from mo_arbor.diff import Diff
from mo_arbor.diff import diff
from mo_arbor.dumps import DumpNotFound
from mo_arbor.dumps import Dumps

router = APIRouter()
logger = structlog.stdlib.get_logger()


class Ingested(BaseModel):
    file_name: str
    added: list[str]
    changed: list[str]
    removed: list[str]


# Removed units get this minus their depth as priority, while new and changed
# units get their depth, so terminations come after every creation and update.
# The exact value does not matter, as long as it is above every depth. Events in
# the wrong order still work, they are just retried a few minutes later.
TERMINATION_PRIORITY = 1000


def priorities(
    d: Diff, units: dict[str, Unit], previous: dict[str, Unit]
) -> dict[str, int]:
    """The priority of each user_key's event.

    MO hands out the events with the lowest priority first. Parents come before
    their children, as MO rejects a unit whose parent does not exist. Removed
    units come last, children first, as MO rejects terminating a unit with
    active children.
    """
    return {
        **{user_key: units[user_key].depth for user_key in d.added | d.changed},
        **{
            user_key: TERMINATION_PRIORITY - previous[user_key].depth
            for user_key in d.removed
        },
    }


async def send_events(
    mo: GraphQLClient, code_system: CodeSystem, priorities: dict[str, int]
) -> None:
    async with asyncio.TaskGroup() as tg:
        for user_key, priority in priorities.items():
            tg.create_task(
                mo.send_event(
                    input=EventSendInput(
                        namespace=code_system.name,
                        routing_key="org_unit",
                        subject=user_key,
                        priority=priority,
                    )
                )
            )


async def ingest_code_system(
    code_system: CodeSystem,
    mo: GraphQLClient,
    dumps: Dumps,
    sessionmaker: async_sessionmaker[AsyncSession],
    dry_run: bool,
    force: bool,
) -> Ingested | None:
    log = logger.bind(code_system=code_system.name)
    listing = await dumps.listing(mo)
    if not listing:
        return None
    _, file_name = listing[-1]

    async with sessionmaker() as session:
        last = await session.get(LastApplied, code_system.name)
    if last is not None and last.file_name == file_name:
        return None

    try:
        dump = await dumps.load(mo, file_name)
    except InvalidFile as e:
        log.error("Invalid dump", file_name=file_name, error=str(e))
        return None
    # Without a last ingested dump, an event is sent for every unit in the
    # newest dump
    previous = None
    if last is not None:
        # Without it, the units removed since cannot be found
        try:
            previous = await dumps.load(mo, last.file_name)
        except DumpNotFound:
            log.error("Last ingested dump not found", file_name=last.file_name)
            return None
        except InvalidFile as e:
            log.error(
                "Invalid last ingested dump", file_name=last.file_name, error=str(e)
            )
            return None

    d = diff(previous.units if previous else None, dump.units)
    if len(d.removed) > code_system.max_terminations and not force:
        log.error(
            "Too many terminations in dump",
            file_name=file_name,
            terminations=len(d.removed),
            max_terminations=code_system.max_terminations,
        )
        return None

    ingested = Ingested(
        file_name=file_name,
        added=sorted(d.added),
        changed=sorted(d.changed),
        removed=sorted(d.removed),
    )
    if dry_run:
        return ingested

    log.info(
        "Ingesting dump",
        file_name=file_name,
        added=len(d.added),
        changed=len(d.changed),
        removed=len(d.removed),
    )
    # Events are sent before the dump is recorded, so if we crash in between,
    # the next ingest sends them again rather than losing them. An event sent
    # twice is harmless, as the handler reads the newest dump either way.
    await send_events(
        mo, code_system, priorities(d, dump.units, previous.units if previous else {})
    )
    async with sessionmaker() as session, session.begin():
        await session.execute(
            insert(LastApplied)
            .values(code_system=code_system.name, file_name=file_name)
            .on_conflict_do_update(
                index_elements=[LastApplied.code_system],
                set_={"file_name": file_name},
            )
        )
    return ingested


@router.post("/ingest")
async def ingest(
    settings: depends.Settings,
    mo: depends.GraphQLClient,
    all_dumps: depends.AllDumps,
    sessionmaker: Sessionmaker,
    code_system: str | None = None,
    dry_run: bool = False,
    force: bool = False,
) -> dict[str, Ingested | None]:
    """Send a unit event for each unit that changed since the last ingest.

    Every code system is ingested, or only `code_system` if set. The newest
    dump of a code system is compared to its last ingested one. Dumps in
    between are skipped, as the event handler always reads the newest dump.

    Nothing is ingested for a code system whose newest dump is invalid, whose
    last ingested dump is gone or invalid, or whose newest dump removes more
    than its `max_terminations` units unless `force` is set. These are logged
    as errors.

    With `dry_run`, returns what would be ingested without sending events or
    recording anything.
    """
    code_systems = [c for c in settings.code_systems if code_system in (None, c.name)]
    if not code_systems:
        raise HTTPException(status_code=404, detail="Unknown code system")
    return {
        c.name: await ingest_code_system(
            c, mo, all_dumps[c.name], sessionmaker, dry_run=dry_run, force=force
        )
        for c in code_systems
    }
