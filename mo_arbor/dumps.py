"""Code system files in MO's file store.

The supplier uploads the files to the EXPORTS file store, with the time of the
dump in the file name.
"""

import base64
from collections.abc import Callable
from datetime import date
from datetime import datetime

from async_lru import alru_cache
from pydantic import BaseModel

from mo_arbor.autogenerated_graphql_client import FileStore
from mo_arbor.autogenerated_graphql_client import GraphQLClient
from mo_arbor.code_system_file import InvalidFile
from mo_arbor.code_system_file import TopUnit
from mo_arbor.code_system_file import Unit
from mo_arbor.code_system_file import parse


class DumpNotFound(Exception):
    pass


class Dump(BaseModel, frozen=True):
    file_name: str
    date: date
    units: dict[str, Unit]


def dump_time(file_name: str, pattern: str) -> datetime | None:
    """Return the time of the dump from a file name, or None if it is not one."""
    try:
        # File names have no time zone
        return datetime.strptime(file_name, pattern)  # noqa: DTZ007
    except ValueError:
        return None


def decode(base64_contents: str) -> str:
    """Decode a file from the file store.

    Raises:
        InvalidFile: If the file is not UTF-8.
    """
    try:
        # The supplier's files start with a byte order mark, which utf-8-sig
        # removes
        return base64.b64decode(base64_contents).decode("utf-8-sig")
    except UnicodeDecodeError as e:
        raise InvalidFile(f"not UTF-8: {e}") from None


class Dumps:
    """Lists, reads and parses the dumps of a code system in the file store."""

    def __init__(
        self,
        pattern: str,
        is_valid_code: Callable[[str], bool] | None = None,
        top_unit: TopUnit | None = None,
    ) -> None:
        self.pattern = pattern
        self.is_valid_code = is_valid_code
        self.top_unit = top_unit
        # Each event reads the newest dump, and ingest also the previous one.
        # Errors are not cached, so a fixed dump uploaded again is read again.
        self.load = alru_cache(maxsize=2)(self._load)

    async def listing(self, mo: GraphQLClient) -> list[tuple[datetime, str]]:
        """List the dumps in the file store, oldest first."""
        files = await mo.list_files(FileStore.EXPORTS)
        dumps = []
        for file in files.objects:
            time = dump_time(file.file_name, self.pattern)
            if time is not None:
                dumps.append((time, file.file_name))
        return sorted(dumps)

    async def newest(self, mo: GraphQLClient) -> Dump:
        """Load and parse the newest dump.

        Raises:
            DumpNotFound: If there are no dumps.
            InvalidFile: If the dump fails validation.
        """
        dumps = await self.listing(mo)
        if not dumps:
            raise DumpNotFound("there are no dumps in the file store")
        _, file_name = dumps[-1]
        return await self.load(mo, file_name)

    async def _load(self, mo: GraphQLClient, file_name: str) -> Dump:
        """Load and parse a dump.

        Raises:
            DumpNotFound: If there is no dump with this name.
            InvalidFile: If the dump is not UTF-8, or fails validation.
        """
        time = dump_time(file_name, self.pattern)
        if time is None:
            raise DumpNotFound(f"{file_name} does not match {self.pattern}")
        files = await mo.read_file(FileStore.EXPORTS, file_name)
        if not files.objects:
            raise DumpNotFound(f"{file_name} is not in the file store")
        text = decode(files.objects[0].base64_contents)
        units = parse(text, self.is_valid_code, self.top_unit)
        return Dump(file_name=file_name, date=time.date(), units=units)
