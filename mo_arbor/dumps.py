"""Code system files in MO's file store.

The supplier uploads the files to the EXPORTS file store, with the code
system's name and the time of the dump at the end of the file name.
"""

import base64
import re
from datetime import date
from datetime import datetime

from async_lru import alru_cache
from more_itertools import one
from pydantic import BaseModel

from mo_arbor.autogenerated_graphql_client import FileStore
from mo_arbor.autogenerated_graphql_client import GraphQLClient
from mo_arbor.code_system_file import InvalidFile
from mo_arbor.code_system_file import Rows
from mo_arbor.code_system_file import Unit


class DumpNotFound(Exception):
    pass


class Dump(BaseModel, frozen=True):
    file_name: str
    date: date
    units: dict[str, Unit]


def decode(base64_contents: str) -> str:
    """Decode a file from the file store.

    Raises:
        InvalidFile: If the file is not UTF-8.
    """
    try:
        # The supplier's files start with a byte order mark, which utf-8-sig
        # removes
        return base64.b64decode(base64_contents).decode("utf-8-sig")
    except UnicodeDecodeError as e:
        raise InvalidFile(f"not UTF-8: {e}") from e


class DumpStore:
    """Finds, loads and parses the dumps of a code system in the file store.

    A dump's file name ends in the code system's name and the time of the
    dump, after any prefix, such as the customer's name, e.g.
    customer_sor_20261016_094303.csv.
    """

    def __init__(self, code_system: str, rows_model: type[Rows] = Rows) -> None:
        self.code_system = code_system
        self.pattern = re.compile(
            rf"(?:.*_)?{re.escape(code_system)}_(\d{{8}}_\d{{6}})\.csv"
        )
        self.rows_model = rows_model
        # Each event reads the newest dump, and ingest also the previous one.
        # Errors are not cached, so a fixed dump uploaded again is read again.
        # Each code system has its own cache, which a decorator on the method
        # would share between them.
        self.load = alru_cache(maxsize=2)(self._load)

    def dump_time(self, file_name: str) -> datetime | None:
        """The time of the dump in a file name, or None if it is not a dump."""
        match = self.pattern.fullmatch(file_name)
        if match is None:
            return None
        try:
            # File names have no time zone
            return datetime.strptime(match[1], "%Y%m%d_%H%M%S")
        except ValueError:
            return None

    async def newest_file_name(self, mo: GraphQLClient) -> str:
        """The file name of the newest dump in the file store.

        Raises:
            DumpNotFound: If there are no dumps.
        """
        files = await mo.list_files(FileStore.EXPORTS)
        dumps = []
        for file in files.objects:
            time = self.dump_time(file.file_name)
            if time is not None:
                dumps.append((time, file.file_name))
        if not dumps:
            raise DumpNotFound(f"no dumps of {self.code_system}")
        _, file_name = max(dumps)
        return file_name

    async def load_newest(self, mo: GraphQLClient) -> Dump:
        """Load and parse the newest dump.

        Raises:
            DumpNotFound: If there are no dumps.
            InvalidFile: If the dump is not UTF-8, or fails validation.
        """
        return await self.load(mo, await self.newest_file_name(mo))

    async def _load(self, mo: GraphQLClient, file_name: str) -> Dump:
        """Load and parse a dump.

        Raises:
            DumpNotFound: If there is no dump with this name.
            InvalidFile: If the dump is not UTF-8, or fails validation.
        """
        # The dump's date is in its name
        time = self.dump_time(file_name)
        if time is None:
            raise DumpNotFound(f"{file_name} is not a dump of {self.code_system}")
        files = await mo.read_file(FileStore.EXPORTS, file_name)
        file = one(
            files.objects,
            too_short=DumpNotFound(f"{file_name} is not in the file store"),
        )
        try:
            text = decode(file.base64_contents)
            units = self.rows_model.parse(text)
        except InvalidFile as e:
            raise InvalidFile(f"{file_name}: {e}") from e
        return Dump(file_name=file_name, date=time.date(), units=units)
