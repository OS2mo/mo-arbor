from datetime import timedelta

import structlog
from fastapi import APIRouter
from fastapi import HTTPException
from fastramqpi.events import Event

from mo_arbor import depends
from mo_arbor.autogenerated_graphql_client import OrganisationUnitCreateInput
from mo_arbor.autogenerated_graphql_client import OrganisationUnitTerminateInput
from mo_arbor.autogenerated_graphql_client import OrganisationUnitUpdateInput
from mo_arbor.autogenerated_graphql_client import RAValidityInput
from mo_arbor.mo import get_class
from mo_arbor.mo import mo_datetime
from mo_arbor.mo import unit_end

router = APIRouter()
logger = structlog.stdlib.get_logger()


@router.post("/{code_system}/org_unit")
async def handle_unit(
    code_system: str,
    settings: depends.Settings,
    mo: depends.GraphQLClient,
    all_dumps: depends.AllDumps,
    event: Event[str],
) -> None:
    """Make the org unit with this user_key match the code system's newest dump.

    The newest dump is read rather than the one the event came from, so an old
    or repeated event never writes outdated data. Changes take effect from the
    dump's date, and the unit ends at its validity_to.
    """
    system = next((c for c in settings.code_systems if c.name == code_system), None)
    if system is None:
        raise HTTPException(status_code=404, detail="Unknown code system")
    dumps = all_dumps[system.name]
    user_key = event.subject
    log = logger.bind(code_system=system.name, user_key=user_key)

    dump = await dumps.newest(mo)
    file_name = dump.file_name
    unit = dump.units.get(user_key)

    uuid = system.uuid(user_key)
    org_units = await mo.get_org_unit(uuid)
    # The unit has existed in MO, though it might be terminated now
    exists = bool(org_units.objects)
    current = org_units.objects[0].current if exists else None

    if unit is None:
        if current is not None:
            log.info("Terminating org unit", file_name=file_name)
            # MO's end dates are exclusive, so the unit's last day is the day
            # before the dump
            await mo.terminate_org_unit(
                OrganisationUnitTerminateInput(uuid=uuid, to=mo_datetime(dump.date))
            )
        return

    parent = system.uuid(unit.parent_user_key) if unit.parent_user_key else None
    unit_type = await get_class(mo, "org_unit_type", unit.org_unit_type)
    org_unit_level = await get_class(mo, "org_unit_level", unit.org_unit_level)
    # MO's end dates are exclusive, so the unit ends the day after its last day
    end = unit.end + timedelta(days=1) if unit.end is not None else None

    if not exists:
        log.info("Creating org unit", file_name=file_name)
        await mo.create_org_unit(
            OrganisationUnitCreateInput(
                uuid=uuid,
                user_key=user_key,
                name=unit.name,
                parent=parent,
                org_unit_type=unit_type,
                org_unit_level=org_unit_level,
                validity=RAValidityInput(
                    from_=mo_datetime(unit.start),
                    to=mo_datetime(end) if end is not None else None,
                ),
            )
        )
        return

    if end is not None and end <= dump.date:
        # The unit ended before the dump, so only its end is written
        if current is not None:
            log.info("Terminating org unit at its end", file_name=file_name)
            await mo.terminate_org_unit(
                OrganisationUnitTerminateInput(uuid=uuid, to=mo_datetime(end))
            )
        return

    mo_end = unit_end([v.validity.to for v in org_units.objects[0].validities])
    changed = current is None or (
        current.user_key,
        current.name,
        current.parent.uuid if current.parent else None,
        current.unit_type.uuid if current.unit_type else None,
        current.org_unit_level.uuid if current.org_unit_level else None,
    ) != (user_key, unit.name, parent, unit_type, org_unit_level)
    if not changed and mo_end == end:
        log.debug("Org unit is up to date")
        return

    # A termination cannot move an end later, but an open-ended update removes
    # it. The update also reopens a terminated unit, as MO makes the unit active
    # from the update's start.
    if changed or (mo_end is not None and (end is None or end > mo_end)):
        log.info("Updating org unit", file_name=file_name)
        await mo.update_org_unit(
            OrganisationUnitUpdateInput(
                uuid=uuid,
                user_key=user_key,
                name=unit.name,
                parent=parent,
                org_unit_type=unit_type,
                org_unit_level=org_unit_level,
                # A unit that starts after the dump is not valid before it
                validity=RAValidityInput(from_=mo_datetime(max(unit.start, dump.date))),
            )
        )
    if end is not None:
        log.info("Ending org unit", file_name=file_name, end=unit.end)
        await mo.terminate_org_unit(
            OrganisationUnitTerminateInput(uuid=uuid, to=mo_datetime(end))
        )
