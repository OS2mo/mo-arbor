from mo_arbor.mo import mo_datetime
from mo_arbor.mo import unit_end

router = APIRouter()
logger = structlog.stdlib.get_logger()


class Values(BaseModel, frozen=True):
    """The values of an org unit compared between the dump and MO.

    They are set in MO when they differ. The validity is not among them, as
    MO's current values are those of the current period, which starts at the
    last change and may end at a planned one. The unit's end is compared with
    the end of its last period instead.
    """

    user_key: str
    name: str
    parent: UUID | None
    org_unit_type: UUID | None
    org_unit_level: UUID | None


async def values_from_dump(
    mo: GraphQLClient, code_system: CodeSystem, dump_unit: Unit
) -> Values:
    return Values(
        user_key=dump_unit.user_key,
        name=dump_unit.name,
        parent=code_system.parent_uuid(dump_unit),
        org_unit_type=await get_class(mo, "org_unit_type", dump_unit.org_unit_type),
        org_unit_level=await get_class(mo, "org_unit_level", dump_unit.org_unit_level),
    )


def values_in_mo(current: GetOrgUnitOrgUnitsObjectsCurrent) -> Values:
    parent = current.parent_response
    unit_type = current.unit_type_response
    unit_level = current.unit_level_response
    return Values(
        user_key=current.user_key,
        name=current.name,
        parent=parent.uuid if parent else None,
        org_unit_type=unit_type.uuid if unit_type else None,
        org_unit_level=unit_level.uuid if unit_level else None,
    )


def first_day_terminated(dump_unit: Unit) -> date | None:
    """The day after the unit's last day, as MO's end dates are exclusive."""
    return dump_unit.end + timedelta(days=1) if dump_unit.end is not None else None


@router.post("/{code_system_name}/org_unit")
async def handle_unit(
    code_system_name: str,
    settings: depends.Settings,
    mo: depends.GraphQLClient,
    dump_stores: depends.DumpStores,
    event: Event[str],
) -> None:
    """Make the org unit with this user_key match the code system's newest dump.

    The newest dump is read rather than the one the event came from, so an old
    or repeated event never writes outdated data. Changes take effect from the
    dump's date, and the unit ends at its validity_to. A unit MO ended, which
    the dump says was active then, is active again from where MO ended it.
    """
    code_system = settings.get_code_system(code_system_name)
    if code_system is None:
        raise HTTPException(status_code=404, detail="Unknown code system")
    dump = await dump_stores[code_system.name].newest(mo)
    user_key = event.subject
    log = logger.bind(
        code_system=code_system.name, user_key=user_key, file_name=dump.file_name
    )
    dump_unit = dump.units.get(user_key)
    uuid = code_system.org_unit_uuid(user_key)
    # Not None if the unit has existed in MO, though it might have ended
    mo_unit = only((await mo.get_org_unit(uuid)).objects)

    match mo_unit, dump_unit:
        case None, Unit():
            log.info("Creating org unit")
            await create(mo, code_system, uuid, dump_unit)
        case None, _:
            # In neither, such as an old event for a unit removed before it
            # was made
            pass
        case _, None:
            # Removed from the dump
            await terminate(mo, uuid, mo_unit, dump.date, log)
        case _, _:
            await update(mo, code_system, uuid, dump_unit, mo_unit, dump.date, log)
            terminated_from = first_day_terminated(dump_unit)
            if terminated_from is not None:
                # Only a termination can move an end earlier, as MO leaves the
                # unit as it was after the update's end. So a dump from April
                # that renames the unit and moves its end from 1 October to
                # 1 May takes both:
                #
                #                       April         1 May         1 October
                #   MO:         Afdeling -------------------------------|
                #   update:     Afdeling --|Renamed ----|Afdeling ------|
                #   terminate:  Afdeling --|Renamed ----|
                #
                # terminate() does nothing when MO already ends the unit by
                # then, such as after an update that moved the end later.
                await terminate(mo, uuid, mo_unit, terminated_from, log)


async def create(
    mo: GraphQLClient, code_system: CodeSystem, uuid: UUID, dump_unit: Unit
) -> None:
    values = await values_from_dump(mo, code_system, dump_unit)
    terminated_from = first_day_terminated(dump_unit)
    to = mo_datetime(terminated_from) if terminated_from is not None else None
    await mo.create_org_unit(
        OrganisationUnitCreateInput(
            uuid=uuid,
            **values.dict(),
            validity=RAValidityInput(from_=mo_datetime(dump_unit.start), to=to),
        )
    )


async def terminate(
    mo: GraphQLClient,
    uuid: UUID,
    mo_unit: GetOrgUnitOrgUnitsObjects,
    terminated_from: date,
    log: structlog.stdlib.BoundLogger,
) -> None:
    """Terminate the unit from `terminated_from`, unless it has ended by then.

    A unit that starts later is terminated from its start, as MO rejects an end
    before the start.
    """
    mo_terminated_from = unit_end({v.validity.to for v in mo_unit.validities})
    if mo_terminated_from is not None and mo_terminated_from <= terminated_from:
        return
    start = min(v.validity.from_ for v in mo_unit.validities).date()
    log.info("Terminating org unit", terminated_from=terminated_from)
    await mo.terminate_org_unit(
        OrganisationUnitTerminateInput(
            uuid=uuid, to=mo_datetime(max(terminated_from, start))
        )
    )


async def update(
    mo: GraphQLClient,
    code_system: CodeSystem,
    uuid: UUID,
    dump_unit: Unit,
    mo_unit: GetOrgUnitOrgUnitsObjects,
    dump_date: date,
    log: structlog.stdlib.BoundLogger,
) -> None:
    """Update the unit from the dump's date until its end.

    MO makes the unit active for the whole update, so the update also moves an
    end later, removes it, or reopens an ended unit. An end that moves earlier
    is left to a termination.

    A unit MO ended, which the dump says was active then, is updated from where
    MO ended it instead, so it has no gap. Such as a unit back in the dump after
    a dump left it out.
    """
    terminated_from = first_day_terminated(dump_unit)
    mo_terminated_from = unit_end({v.validity.to for v in mo_unit.validities})
    # A unit that starts after the dump is not valid before it
    from_ = max(dump_unit.start, dump_date)
    if mo_terminated_from is not None and (
        dump_unit.start <= mo_terminated_from < from_
    ):
        from_ = mo_terminated_from
    if terminated_from is not None and terminated_from <= from_:
        # Ended by then, which is left to a termination
        return

    values = await values_from_dump(mo, code_system, dump_unit)
    changed = mo_unit.current is None or values_in_mo(mo_unit.current) != values
    ends_later = mo_terminated_from is not None and (
        terminated_from is None or terminated_from > mo_terminated_from
    )
    if not changed and not ends_later:
        return

    log.info("Updating org unit")
    to = mo_datetime(terminated_from) if terminated_from is not None else None
    await mo.update_org_unit(
        OrganisationUnitUpdateInput(
            uuid=uuid,
            **values.dict(),
            validity=RAValidityInput(from_=mo_datetime(from_), to=to),
        )
    )
