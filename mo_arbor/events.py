from datetime import date
from datetime import timedelta
from uuid import UUID

import structlog
from fastapi import APIRouter
from fastapi import HTTPException
from fastramqpi.events import Event
from more_itertools import only
from pydantic import BaseModel

from mo_arbor import depends
from mo_arbor.autogenerated_graphql_client import GetOrgUnitOrgUnitsObjects
from mo_arbor.autogenerated_graphql_client import GetOrgUnitOrgUnitsObjectsCurrent
from mo_arbor.autogenerated_graphql_client import GraphQLClient
from mo_arbor.autogenerated_graphql_client import OrganisationUnitCreateInput
from mo_arbor.autogenerated_graphql_client import OrganisationUnitTerminateInput
from mo_arbor.autogenerated_graphql_client import OrganisationUnitUpdateInput
from mo_arbor.autogenerated_graphql_client import RAValidityInput
from mo_arbor.code_system_file import Unit
from mo_arbor.config import CodeSystem
from mo_arbor.mo import get_class
from mo_arbor.mo import mo_datetime
from mo_arbor.mo import unit_end

router = APIRouter()
logger = structlog.stdlib.get_logger()


class Values(BaseModel, frozen=True):
    """The values of an org unit compared between the dump and MO.

    They are set in MO when they differ. The validity is handled on its own.
    """

    user_key: str
    name: str
    parent: UUID | None
    org_unit_type: UUID | None
    org_unit_level: UUID | None


async def values_from_dump(
    mo: GraphQLClient, code_system: CodeSystem, unit: Unit
) -> Values:
    return Values(
        user_key=unit.user_key,
        name=unit.name,
        parent=code_system.parent_uuid(unit),
        org_unit_type=await get_class(mo, "org_unit_type", unit.org_unit_type),
        org_unit_level=await get_class(mo, "org_unit_level", unit.org_unit_level),
    )


def values_in_mo(current: GetOrgUnitOrgUnitsObjectsCurrent) -> Values:
    parent = current.parent_response
    unit_type = current.unit_type_response
    unit_level = current.unit_level_response
    return Values(
        user_key=current.user_key,
        name=current.name,
        parent=parent.uuid if parent else None,
        org_unit_type=unit_type.uuid if unit_type else None,
        org_unit_level=unit_level.uuid if unit_level else None,
    )


def first_day_terminated(unit: Unit) -> date | None:
    """The day after the unit's last day, as MO's end dates are exclusive."""
    return unit.end + timedelta(days=1) if unit.end is not None else None


@router.post("/{code_system_name}/org_unit")
async def handle_unit(
    code_system_name: str,
    settings: depends.Settings,
    mo: depends.GraphQLClient,
    dump_stores: depends.DumpStores,
    event: Event[str],
) -> None:
    """Make the org unit with this user_key match the code system's newest dump.

    The newest dump is read rather than the one the event came from, so an old
    or repeated event never writes outdated data. Changes take effect from the
    dump's date, and the unit ends at its validity_to.
    """
    code_system = settings.get_code_system(code_system_name)
    if code_system is None:
        raise HTTPException(status_code=404, detail="Unknown code system")
    dump = await dump_stores[code_system.name].newest(mo)
    user_key = event.subject
    log = logger.bind(
        code_system=code_system.name, user_key=user_key, file_name=dump.file_name
    )
    unit = dump.units.get(user_key)
    uuid = code_system.org_unit_uuid(user_key)
    # Not None if the unit has existed in MO, though it might have ended
    org_unit = only((await mo.get_org_unit(uuid)).objects)

    if org_unit is None:
        if unit is not None:
            log.info("Creating org unit")
            await create(mo, code_system, uuid, unit)
        return
    if unit is None:
        # Removed from the dump
        await terminate(mo, uuid, org_unit, dump.date, log)
        return
    terminated_from = first_day_terminated(unit)
    if terminated_from is not None and terminated_from <= dump.date:
        # Ended before the dump
        await terminate(mo, uuid, org_unit, terminated_from, log)
        return
    await update(mo, code_system, uuid, unit, org_unit, dump.date, log)
    if terminated_from is not None:
        # Only a termination can move an end earlier, as MO leaves the unit as
        # it was after the update's end. So a dump from April that renames the
        # unit and moves its end from 1 October to 1 May takes both:
        #
        #                           April           1 May           1 October
        #   MO:         Afdeling -----------------------------------|
        #   update:     Afdeling ---|Renamed -------|Afdeling ------|
        #   terminate:  Afdeling ---|Renamed -------|
        #
        # terminate() does nothing when MO already ends the unit by then, such
        # as after an update that moved the end later.
        await terminate(mo, uuid, org_unit, terminated_from, log)


async def create(
    mo: GraphQLClient, code_system: CodeSystem, uuid: UUID, unit: Unit
) -> None:
    values = await values_from_dump(mo, code_system, unit)
    terminated_from = first_day_terminated(unit)
    to = mo_datetime(terminated_from) if terminated_from is not None else None
    await mo.create_org_unit(
        OrganisationUnitCreateInput(
            uuid=uuid,
            **values.dict(),
            validity=RAValidityInput(from_=mo_datetime(unit.start), to=to),
        )
    )


async def terminate(
    mo: GraphQLClient,
    uuid: UUID,
    org_unit: GetOrgUnitOrgUnitsObjects,
    terminated_from: date,
    log: structlog.stdlib.BoundLogger,
) -> None:
    """Terminate the unit from `terminated_from`, unless it has ended by then.

    A unit that starts later is terminated from its start, as MO rejects an end
    before the start.
    """
    mo_terminated_from = unit_end([v.validity.to for v in org_unit.validities])
    if mo_terminated_from is not None and mo_terminated_from <= terminated_from:
        return
    start = min(v.validity.from_ for v in org_unit.validities).date()
    log.info("Terminating org unit", terminated_from=terminated_from)
    await mo.terminate_org_unit(
        OrganisationUnitTerminateInput(
            uuid=uuid, to=mo_datetime(max(terminated_from, start))
        )
    )


async def update(
    mo: GraphQLClient,
    code_system: CodeSystem,
    uuid: UUID,
    unit: Unit,
    org_unit: GetOrgUnitOrgUnitsObjects,
    dump_date: date,
    log: structlog.stdlib.BoundLogger,
) -> None:
    """Update the unit from the dump's date until its end.

    MO makes the unit active for the whole update, so the update also moves an
    end later, removes it, or reopens an ended unit. An end that moves earlier
    is left to a termination.
    """
    values = await values_from_dump(mo, code_system, unit)
    changed = org_unit.current is None or values_in_mo(org_unit.current) != values
    terminated_from = first_day_terminated(unit)
    mo_terminated_from = unit_end([v.validity.to for v in org_unit.validities])
    ends_later = mo_terminated_from is not None and (
        terminated_from is None or terminated_from > mo_terminated_from
    )
    if not changed and not ends_later:
        return

    log.info("Updating org unit")
    to = mo_datetime(terminated_from) if terminated_from is not None else None
    await mo.update_org_unit(
        OrganisationUnitUpdateInput(
            uuid=uuid,
            **values.dict(),
            # A unit that starts after the dump is not valid before it
            validity=RAValidityInput(
                from_=mo_datetime(max(unit.start, dump_date)), to=to
            ),
        )
    )
