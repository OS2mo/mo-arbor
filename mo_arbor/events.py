from datetime import date
from datetime import timedelta
from uuid import UUID

import structlog
from fastapi import APIRouter
from fastapi import HTTPException
from fastramqpi.events import Event
from more_itertools import only
from pydantic import BaseModel

from mo_arbor import depends
from mo_arbor.autogenerated_graphql_client import GraphQLClient
from mo_arbor.autogenerated_graphql_client import OrganisationUnitCreateInput
from mo_arbor.autogenerated_graphql_client import RAValidityInput
from mo_arbor.code_system_file import Unit
from mo_arbor.config import CodeSystem
from mo_arbor.mo import get_class
from mo_arbor.mo import mo_datetime

router = APIRouter()
logger = structlog.stdlib.get_logger()


class Values(BaseModel, frozen=True):
    """The values of an org unit that are set in MO from the dump.

    The validity is handled on its own.
    """

    user_key: str
    name: str
    parent: UUID | None
    org_unit_type: UUID | None
    org_unit_level: UUID | None


async def values_from_dump(
    mo: GraphQLClient, code_system: CodeSystem, unit: Unit
) -> Values:
    return Values(
        user_key=unit.user_key,
        name=unit.name,
        parent=code_system.parent_uuid(unit),
        org_unit_type=await get_class(mo, "org_unit_type", unit.org_unit_type),
        org_unit_level=await get_class(mo, "org_unit_level", unit.org_unit_level),
    )


def first_day_terminated(unit: Unit) -> date | None:
    """The day after the unit's last day, as MO's end dates are exclusive."""
    return unit.end + timedelta(days=1) if unit.end is not None else None


@router.post("/{code_system_name}/org_unit")
async def handle_unit(
    code_system_name: str,
    settings: depends.Settings,
    mo: depends.GraphQLClient,
    dump_stores: depends.DumpStores,
    event: Event[str],
) -> None:
    """Create the org unit with this user_key from the code system's newest dump.

    The newest dump is read rather than the one the event came from, so an old
    or repeated event never writes outdated data.
    """
    code_system = settings.get_code_system(code_system_name)
    if code_system is None:
        raise HTTPException(status_code=404, detail="Unknown code system")
    dump = await dump_stores[code_system.name].newest(mo)
    user_key = event.subject
    log = logger.bind(
        code_system=code_system.name, user_key=user_key, file_name=dump.file_name
    )
    unit = dump.units.get(user_key)
    uuid = code_system.org_unit_uuid(user_key)
    # Not None if the unit has existed in MO, though it might have ended
    org_unit = only((await mo.get_org_unit(uuid)).objects)

    if org_unit is None and unit is not None:
        log.info("Creating org unit")
        await create(mo, code_system, uuid, unit)


async def create(
    mo: GraphQLClient, code_system: CodeSystem, uuid: UUID, unit: Unit
) -> None:
    values = await values_from_dump(mo, code_system, unit)
    terminated_from = first_day_terminated(unit)
    to = mo_datetime(terminated_from) if terminated_from is not None else None
    await mo.create_org_unit(
        OrganisationUnitCreateInput(
            uuid=uuid,
            **values.dict(),
            validity=RAValidityInput(from_=mo_datetime(unit.start), to=to),
        )
    )
