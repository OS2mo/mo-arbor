from datetime import timedelta
from uuid import UUID

import structlog
from fastapi import APIRouter
from fastapi import HTTPException
from fastramqpi.events import Event
from more_itertools import only
from pydantic import BaseModel

from mo_arbor import depends
from mo_arbor.autogenerated_graphql_client import GetOrgUnitOrgUnitsObjects
from mo_arbor.autogenerated_graphql_client import GetOrgUnitOrgUnitsObjectsCurrent
from mo_arbor.autogenerated_graphql_client import GraphQLClient
from mo_arbor.autogenerated_graphql_client import OrganisationUnitCreateInput
from mo_arbor.autogenerated_graphql_client import OrganisationUnitTerminateInput
from mo_arbor.autogenerated_graphql_client import OrganisationUnitUpdateInput
from mo_arbor.autogenerated_graphql_client import RAValidityInput
from mo_arbor.code_system_file import Unit
from mo_arbor.config import CodeSystem
