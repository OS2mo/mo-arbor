from datetime import date
from datetime import timedelta
from uuid import UUID

import structlog
from fastapi import APIRouter
from fastapi import HTTPException
from fastramqpi.events import Event
from more_itertools import only
from pydantic import BaseModel

from mo_arbor import depends
from mo_arbor.autogenerated_graphql_client import GetOrgUnitOrgUnitsObjects
from mo_arbor.autogenerated_graphql_client import GetOrgUnitOrgUnitsObjectsCurrent
from mo_arbor.autogenerated_graphql_client import GraphQLClient
from mo_arbor.autogenerated_graphql_client import OrganisationUnitCreateInput
from mo_arbor.autogenerated_graphql_client import OrganisationUnitTerminateInput
from mo_arbor.autogenerated_graphql_client import OrganisationUnitUpdateInput
from mo_arbor.autogenerated_graphql_client import RAValidityInput
from mo_arbor.code_system_file import Unit
from mo_arbor.config import CodeSystem
from mo_arbor.mo import get_class
from mo_arbor.mo import mo_datetime
from mo_arbor.mo import unit_end

router = APIRouter()
logger = structlog.stdlib.get_logger()


class Values(BaseModel, frozen=True):
    """The values the integration sets on an org unit in MO."""

    user_key: str
    name: str
    parent: UUID | None
    org_unit_type: UUID | None
    org_unit_level: UUID | None


async def wanted(mo: GraphQLClient, system: CodeSystem, unit: Unit) -> Values:
    return Values(
        user_key=unit.user_key,
        name=unit.name,
        parent=system.parent(unit),
        org_unit_type=await get_class(mo, "org_unit_type", unit.org_unit_type),
        org_unit_level=await get_class(mo, "org_unit_level", unit.org_unit_level),
    )


def in_mo(current: GetOrgUnitOrgUnitsObjectsCurrent) -> Values:
    return Values(
        user_key=current.user_key,
        name=current.name,
        parent=current.parent.uuid if current.parent else None,
        org_unit_type=current.unit_type.uuid if current.unit_type else None,
        org_unit_level=current.org_unit_level.uuid if current.org_unit_level else None,
    )


def first_day_gone(unit: Unit) -> date | None:
    """The day after the unit's last day, as MO's end dates are exclusive."""
    return unit.end + timedelta(days=1) if unit.end is not None else None


@router.post("/{code_system}/org_unit")
async def handle_unit(
    code_system: str,
    settings: depends.Settings,
    mo: depends.GraphQLClient,
    dump_stores: depends.DumpStores,
    event: Event[str],
) -> None:
    """Make the org unit with this user_key match the code system's newest dump.

    The newest dump is read rather than the one the event came from, so an old
    or repeated event never writes outdated data. Changes take effect from the
    dump's date, and the unit ends at its validity_to.
    """
    system = next((c for c in settings.code_systems if c.name == code_system), None)
    if system is None:
        raise HTTPException(status_code=404, detail="Unknown code system")
    dump = await dump_stores[system.name].newest(mo)
    user_key = event.subject
    log = logger.bind(
        code_system=system.name, user_key=user_key, file_name=dump.file_name
    )
    unit = dump.units.get(user_key)
    uuid = system.uuid(user_key)
    # Not None if the unit has existed in MO, though it might have ended
    org_unit = only((await mo.get_org_unit(uuid)).objects)

    if org_unit is None:
        if unit is not None:
            log.info("Creating org unit")
            await create(mo, system, uuid, unit)
        return
    if unit is None:
        # Gone from the dump
        await end(mo, uuid, org_unit, dump.date, log)
        return
    gone = first_day_gone(unit)
    if gone is not None and gone <= dump.date:
        # Ended before the dump
        await end(mo, uuid, org_unit, gone, log)
        return
    await update(mo, system, uuid, unit, org_unit, dump.date, log)


async def create(mo: GraphQLClient, system: CodeSystem, uuid: UUID, unit: Unit) -> None:
    gone = first_day_gone(unit)
    await mo.create_org_unit(
        OrganisationUnitCreateInput(
            uuid=uuid,
            **(await wanted(mo, system, unit)).dict(),
            validity=RAValidityInput(
                from_=mo_datetime(unit.start),
                to=mo_datetime(gone) if gone is not None else None,
            ),
        )
    )


async def end(
    mo: GraphQLClient,
    uuid: UUID,
    org_unit: GetOrgUnitOrgUnitsObjects,
    gone: date,
    log: structlog.stdlib.BoundLogger,
) -> None:
    """Make the unit gone from `gone`, unless it has ended by then.

    A unit that starts later is gone from its start, as MO rejects an end
    before the start.
    """
    mo_gone = unit_end([v.validity.to for v in org_unit.validities])
    if mo_gone is not None and mo_gone <= gone:
        return
    start = min(v.validity.from_ for v in org_unit.validities).date()
    log.info("Terminating org unit", gone=gone)
    await mo.terminate_org_unit(
        OrganisationUnitTerminateInput(uuid=uuid, to=mo_datetime(max(gone, start)))
    )


async def update(
    mo: GraphQLClient,
    system: CodeSystem,
    uuid: UUID,
    unit: Unit,
    org_unit: GetOrgUnitOrgUnitsObjects,
    dump_date: date,
    log: structlog.stdlib.BoundLogger,
) -> None:
    """Update the unit from the dump's date, and end it at its end."""
    values = await wanted(mo, system, unit)
    changed = org_unit.current is None or in_mo(org_unit.current) != values
    gone = first_day_gone(unit)
    mo_gone = unit_end([v.validity.to for v in org_unit.validities])
    if not changed and mo_gone == gone:
        log.debug("Org unit is up to date")
        return

    # A termination cannot move an end later, but an open-ended update removes
    # it. The update also reopens an ended unit, as MO makes the unit active
    # from the update's start.
    if changed or (mo_gone is not None and (gone is None or gone > mo_gone)):
        log.info("Updating org unit")
        await mo.update_org_unit(
            OrganisationUnitUpdateInput(
                uuid=uuid,
                **values.dict(),
                # A unit that starts after the dump is not valid before it
                validity=RAValidityInput(from_=mo_datetime(max(unit.start, dump_date))),
            )
        )
    if gone is not None:
        log.info("Ending org unit", gone=gone)
        await mo.terminate_org_unit(
            OrganisationUnitTerminateInput(uuid=uuid, to=mo_datetime(gone))
        )
