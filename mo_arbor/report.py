router = APIRouter()
logger = structlog.stdlib.get_logger()


class RootNotFound(Exception):
    pass


class Period(BaseModel, frozen=True):
    """A validity in MO, from its first day until `end`, which is not part of it."""

    start: date
    end: date | None

    @property
    def empty(self) -> bool:
        """Whether it has no days, as it ends where it starts."""
        return self.end is not None and self.end <= self.start

    def covers(self, day: date) -> bool:
        return self.start <= day and (self.end is None or day < self.end)


class UnitPeriod(Period):
    user_key: str
    name: str


class ReportUnit(BaseModel, frozen=True):
    """A unit's code and name on one day."""

    uuid: UUID
    user_key: str
    name: str


class UnitHistory(BaseModel, frozen=True):
    """A unit with every period it has in MO."""

    uuid: UUID
    periods: tuple[UnitPeriod, ...]

    def at(self, day: date) -> ReportUnit | None:
        """The unit as it was on the day, or None if it was not active."""
        # A unit's periods do not overlap
        period = only(p for p in self.periods if p.covers(day))
        if period is None:
            return None
        return ReportUnit(uuid=self.uuid, user_key=period.user_key, name=period.name)


# The relations of each unit, by its UUID: when, and to which unit
Related = dict[UUID, list[tuple[Period, UUID]]]


class Systems(BaseModel, frozen=True):
    """The names of the systems in the report, as their roots are named in MO."""

    source: str
    adm: str
    target: str


class Chain(BaseModel, frozen=True):
    """A row of the report, which may stop after its source or Adm unit."""

    source: ReportUnit
    adm: ReportUnit | None
    target: ReportUnit | None


class Reported(BaseModel, frozen=True):
    file_name: str
    rows: int


def by_user_key(units: list[ReportUnit]) -> list[ReportUnit]:
    return sorted(units, key=attrgetter("user_key"))


def chains(
    sources: list[ReportUnit],
    adm_units: dict[UUID, ReportUnit],
    target_units: dict[UUID, ReportUnit],
    related: dict[UUID, set[UUID]],
) -> list[Chain]:
    """The chains from each of the code system's units, the sources.

    `related` has each unit's related units. Sorted by code, so a report
    without changes is the same file, and is easy to read.
    """

    def linked(
        unit: ReportUnit | None, units: dict[UUID, ReportUnit]
    ) -> Sequence[ReportUnit | None]:
        """The unit's related units among `units`.

        [None] if there are none, or no unit, so the chain stops there and has
        None for the rest.
        """
        if unit is None:
            return [None]
        found = [units[r] for r in related.get(unit.uuid, ()) if r in units]
        return by_user_key(found) or [None]

    return [
        Chain(source=source, adm=adm, target=target)
        for source in by_user_key(sources)
        for adm in linked(source, adm_units)
        for target in linked(adm, target_units)
    ]


def to_csv(systems: Systems, rows: list[Chain]) -> bytes:
    """The report as agreed with its receiver.

    UTF-8 without a byte order mark, `;` as separator, as names often have
    commas, every field quoted with `"` doubled inside (RFC 4180), and CRLF.
    """
    out = io.StringIO()
    writer = csv.writer(
        out, delimiter=";", quoting=csv.QUOTE_ALL, lineterminator="\r\n"
    )
    writer.writerow(
        [
            "Source_System",
            "Source_Code",
            "Source_Name",
            "Adm_System",
            "Adm_Code",
            "Adm_Name",
            "Target_System",
            "Target_Code",
            "Target_Name",
        ]
    )
    for row in rows:
        source, adm, target = row.source, row.adm, row.target
        writer.writerow(
            [
                systems.source,
                source.user_key,
                source.name,
                systems.adm if adm else "",
                adm.user_key if adm else "",
                adm.name if adm else "",
                systems.target if target else "",
                target.user_key if target else "",
                target.name if target else "",
            ]
        )
    return out.getvalue().encode("utf-8")


def report_file_name(code_system: CodeSystem, time: datetime) -> str:
    """E.g. sor_relations_20261117_120000.csv.

    The code system's name comes first, so the file is not taken for one of
    its dumps, which end in the name and the time.
    """
    return f"{code_system.name}_relations_{time:%Y%m%d_%H%M%S}.csv"


def period(start: datetime, end: datetime | None) -> Period:
    return Period(start=start.date(), end=end.date() if end is not None else None)


async def all_unit_histories(
    mo: GraphQLClient, roots: list[UUID]
) -> list[ListUnitHistoriesOrgUnitsObjects]:
    """The org units that are or were in the trees of the roots, from every page."""
    org_units = []
    cursor = None
    while True:
        page = await mo.list_unit_histories(roots, cursor)
        org_units.extend(page.objects)
        cursor = page.page_info.next_cursor
        if cursor is None:
            return org_units


async def all_relations(
    mo: GraphQLClient, roots: list[UUID]
) -> list[ListRelationsRelatedUnitsObjects]:
    """The relations to units that are or were in the trees of the roots."""
    relations = []
    cursor = None
    while True:
        page = await mo.list_relations(roots, cursor)
        relations.extend(page.objects)
        cursor = page.page_info.next_cursor
        if cursor is None:
            return relations


async def unit_histories(
    mo: GraphQLClient, roots: list[UUID]
) -> dict[UUID, UnitHistory]:
    """The units that are or were in the trees of the roots, with every period.

    A period with no days, such as of a unit terminated on the day it was made,
    is left out, and so is a unit with no other periods, as it was never active.
    """
    units = {}
    for org_unit in await all_unit_histories(mo, roots):
        periods = tuple(
            UnitPeriod(
                **period(v.validity.from_, v.validity.to).dict(),
                user_key=v.user_key,
                name=v.name,
            )
            for v in org_unit.validities
        )
        periods = tuple(p for p in periods if not p.empty)
        if periods:
            units[org_unit.uuid] = UnitHistory(uuid=org_unit.uuid, periods=periods)
    return units


def merged(periods: list[Period]) -> list[Period]:
    """The periods without empty ones, and with those that touch or overlap joined.

    MO splits a relation where the unit's other relations were set.
    """
    result: list[Period] = []
    for p in sorted(periods, key=lambda p: p.start):
        if p.empty:
            continue
        last = result[-1] if result else None
        if last is not None and (last.end is None or p.start <= last.end):
            end = None if last.end is None or p.end is None else max(last.end, p.end)
            result[-1] = Period(start=last.start, end=end)
        else:
            result.append(p)
    return result


async def relations(mo: GraphQLClient, roots: list[UUID]) -> Related:
    """The relations of the units in the trees of the roots, both ways, and when
    each was valid.
    """
    periods: defaultdict[tuple[UUID, UUID], list[Period]] = defaultdict(list)
    for relation in await all_relations(mo, roots):
        for v in relation.validities:
            when = period(v.validity.from_, v.validity.to)
            uuids = {org_unit.uuid for org_unit in v.org_units_response.objects}
            for uuid in uuids:
                for related_uuid in uuids - {uuid}:
                    periods[uuid, related_uuid].append(when)
    related: Related = defaultdict(list)
    for (uuid, related_uuid), unit_periods in periods.items():
        related[uuid].extend((when, related_uuid) for when in merged(unit_periods))
    return dict(related)


async def report_units_in_trees(
    mo: GraphQLClient, top_uuids: list[UUID], day: date
) -> dict[UUID, ReportUnit]:
    """The units active on the day in the trees of the top units."""
    units = await unit_histories(mo, top_uuids)
    return {
        uuid: unit
        for uuid, history in units.items()
        if (unit := history.at(day)) is not None
    }


async def adm_units_and_relations(
    mo: GraphQLClient, root: UUID, day: date
) -> tuple[dict[UUID, ReportUnit], dict[UUID, set[UUID]]]:
    """The Adm units active on the day, and the units each unit was related to.

    Every chain goes through an Adm unit, so their relations are all the
    report needs.
    """
    units = await report_units_in_trees(mo, [root], day)
    related = {
        uuid: {
            related_uuid for when, related_uuid in unit_relations if when.covers(day)
        }
        for uuid, unit_relations in (await relations(mo, [root])).items()
    }
    return units, related


async def mo_roots(mo: GraphQLClient, code_system: CodeSystem) -> list[UUID]:
    """The units at the top of the code system's tree in MO.

    Its root unit, if it has one, else those found among MO's root units by their
    UUIDs, which are derived from their codes.

    Raises:
        RootNotFound: If it has no root unit, and no root in MO.
    """
    if code_system.root_unit is not None:
        return [code_system.root_unit.uuid]
    root_units = await mo.list_root_units()
    roots = [
        org_unit.uuid
        for org_unit in root_units.objects
        if any(
            code_system.org_unit_uuid(v.user_key) == org_unit.uuid
            for v in org_unit.validities
        )
    ]
    if not roots:
        raise RootNotFound(f"no root of {code_system.name} in MO")
    return roots


async def code_system_units(
    mo: GraphQLClient, code_system: CodeSystem, day: date
) -> list[ReportUnit]:
    """The code system's units active on the day in MO.

    They are found as the ingest finds them, under the code system's top
    units, whose UUIDs are derived from their codes. "Historiske enheder" is
    not one of the code system's codes, so it is left out.

    Raises:
        RootNotFound: If it has no root unit, and no root in MO.
    """
    units = await report_units_in_trees(mo, await mo_roots(mo, code_system), day)
    return [
        unit
        for uuid, unit in units.items()
        if code_system.org_unit_uuid(unit.user_key) == uuid
        and unit.user_key != HISTORIC_USER_KEY
    ]


def root_name(units: dict[UUID, ReportUnit], root: UUID) -> str:
    """The name of a tree's root, which names its system in the report.

    Raises:
        RootNotFound: If the root is not among the units, those active now.
    """
    if root not in units:
        raise RootNotFound(f"root {root} is not an active unit in MO")
    return units[root].name


async def last_report(mo: GraphQLClient, code_system: CodeSystem) -> bytes | None:
    """The code system's last report in the file store, or None if there is none.

    The last one MO wrote, rather than the newest name, as the time in the
    name repeats an hour when the clocks go back.
    """
    files = await mo.list_files(FileStore.EXPORTS)
    reports = [
        f
        for f in files.objects
        if f.file_name.startswith(f"{code_system.name}_relations_")
    ]
    if not reports:
        return None
    last = max(reports, key=attrgetter("updated_at"))
    read = await mo.read_file(FileStore.EXPORTS, last.file_name)
    return base64.b64decode(one(read.objects).base64_contents)


async def report_code_system(
    code_system: CodeSystem,
    mo: GraphQLClient,
    report_settings: ReportSettings,
    dry_run: bool,
) -> Reported | None:
    """Upload a report, unless it is the same as the last one in the file store.

    Returns the report, or None if it did not change.

    Raises:
        RootNotFound: If the code system is not in MO, or the Adm or target root
            is not an active unit in MO.
    """
    log = logger.bind(code_system=code_system.name)
    now = datetime.now(tz=MO_TIMEZONE)
    sources = await code_system_units(mo, code_system, now.date())
    adm_units, related = await adm_units_and_relations(
        mo, report_settings.root_adm, now.date()
    )
    target_units = await report_units_in_trees(
        mo, [report_settings.root_target], now.date()
    )
    systems = Systems(
        # Which is also the name of its root in MO
        source=code_system.title,
        adm=root_name(adm_units, report_settings.root_adm),
        target=root_name(target_units, report_settings.root_target),
    )
    rows = chains(sources, adm_units, target_units, related)
    contents = to_csv(systems, rows)
    if await last_report(mo, code_system) == contents:
        return None

    file_name = report_file_name(code_system, now)
    reported = Reported(file_name=file_name, rows=len(rows))
    log.info("Uploading report", file_name=file_name, rows=len(rows), dry_run=dry_run)
    if dry_run:
        return reported
    await upload_file(mo, file_name, contents)
    return reported


@router.post("/report")
async def report(
    settings: depends.Settings,
    mo: depends.GraphQLClient,
    code_system: CodeSystemName | None = None,
    dry_run: bool = False,
) -> dict[str, Reported | None]:
    """Upload a report of how each code system's units link to a target tree.

    Reports every code system in `CODE_SYSTEMS`, or only the one named by
    `code_system`. A report the same as the code system's last one in the file
    store is not uploaded, and is returned as None.

    A code system is not reported if it is not in MO, or if the Adm or target
    root is not an active unit in MO. This is logged as an error, and the
    request fails after the other code systems are reported.

    With `dry_run`, returns what would be uploaded without uploading it.
    """
    if settings.report is None:
        raise HTTPException(status_code=404, detail="Report not configured")
    if code_system is None:
        names = settings.code_systems
    elif code_system in settings.code_systems:
        names = {code_system}
    else:
        raise HTTPException(status_code=404, detail="Code system not configured")

    results: dict[str, Reported | None] = {}
    failed = []
    for name in names:
        try:
            results[name] = await report_code_system(
                CodeSystem(name=name),
                mo,
                settings.report,
                dry_run=dry_run,
            )
        except RootNotFound as e:
            logger.error("Not reported", code_system=name, error=str(e))
            failed.append(name)
    if failed:
        raise HTTPException(
            status_code=500, detail=f"Not reported: {', '.join(failed)}"
        )
    return results
