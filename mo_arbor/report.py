SOR = CodeSystem(name="sor")


class RootNotFound(Exception):
    pass


class Period(BaseModel, frozen=True):
    """A validity in MO, from its first day until `end`, which is not part of it."""

    start: date
    end: date | None

    @property
    def last_day(self) -> date | None:
        """Its last day, or None if it does not end."""
        return self.end - timedelta(days=1) if self.end is not None else None

    @property
    def empty(self) -> bool:
        """Whether it has no days, as it ends where it starts."""
        return self.end is not None and self.end <= self.start

    def covers(self, day: date) -> bool:
        return self.start <= day and (self.end is None or day < self.end)

    def overlap(self, other: "Period") -> "Period | None":
        """The days of both periods, or None if they have none in common."""
        start = max(self.start, other.start)
        ends = [end for end in (self.end, other.end) if end is not None]
        end = min(ends, default=None)
        if end is not None and end <= start:
            return None
        return Period(start=start, end=end)

    def report_day(self, today: date) -> date:
        """Today, or its first day if it has not started, or its last if it has
        ended."""
        if today < self.start:
            return self.start
        if self.end is not None and self.end <= today:
            return self.end - timedelta(days=1)
        return today


class UnitPeriod(Period):
    user_key: str
    name: str


class ReportUnit(BaseModel, frozen=True):
    """A unit's code and name on one day."""

    uuid: UUID
    user_key: str
    name: str


class UnitHistory(BaseModel, frozen=True):
    """A unit with every period it has in MO."""

    uuid: UUID
    periods: tuple[UnitPeriod, ...]

    @property
    def user_key(self) -> str:
        """The user_key of its latest period."""
        return max(self.periods, key=lambda period: period.start).user_key

    def at(self, day: date) -> ReportUnit | None:
        """The unit as it was on the day, or None if it was not active."""
        # A unit's periods do not overlap
        period = only(p for p in self.periods if p.covers(day))
        if period is None:
            return None
        return ReportUnit(uuid=self.uuid, user_key=period.user_key, name=period.name)

    def report_day(self, day: date) -> date:
        """The day, if the unit is active then, else the first day of its next
        period, else its last day."""
        if any(period.covers(day) for period in self.periods):
            return day
        later = [period.start for period in self.periods if period.start > day]
        if later:
            return min(later)
        # Only for mypy, as every period has ended
        ends = [period.end for period in self.periods if period.end is not None]
        return max(ends) - timedelta(days=1)

    def on(self, day: date) -> ReportUnit:
        """The unit as it was on `report_day(day)`."""
        unit = self.at(self.report_day(day))
        # Only for mypy, as the unit is active on its report day
        assert unit is not None
        return unit


# The relations of each unit, by its UUID: when, and to which unit
Related = dict[UUID, list[tuple[Period, UUID]]]


class Relation(BaseModel, frozen=True):
    """A related unit, as it is reported, and when the relation was valid."""

    unit: ReportUnit
    period: Period


class Chain(BaseModel, frozen=True):
    """A row of the report, which may stop after its source or Adm unit."""

    source: ReportUnit
    adm: Relation | None
    loen: Relation | None


class Reported(BaseModel, frozen=True):
    file_name: str
    rows: int


def relations_to(
    unit: UnitHistory, units: dict[UUID, UnitHistory], related: Related
) -> list[tuple[Period, UnitHistory]]:
    """The unit's relations to units among `units`, and when each was valid."""
    return [
        (when, units[related_uuid])
        for when, related_uuid in related.get(unit.uuid, ())
        if related_uuid in units
    ]


def relation_order(relation: Relation | None) -> tuple[str, date, UUID]:
    """By code, then from when, with no relation first.

    Then by UUID, as codes may repeat, so the order never depends on MO's.
    """
    if relation is None:
        return "", date.min, UUID(int=0)
    return relation.unit.user_key, relation.period.start, relation.unit.uuid


def loen_chains(
    sources: list[UnitHistory],
    adm_units: dict[UUID, UnitHistory],
    loen_units: dict[UUID, UnitHistory],
    related: Related,
    today: date,
) -> list[Chain]:
    """The chains from each SOR unit, the sources.

    A row for each relation of a SOR unit to an Adm unit, and for each relation
    of that Adm unit to a løn unit that overlaps it.
    """
    rows = []
    for source in sources:
        adm_relations = relations_to(source, adm_units, related)
        if not adm_relations:
            rows.append(Chain(source=source.on(today), adm=None, loen=None))
        for adm_period, adm in adm_relations:
            loen_relations = [
                (loen_period, loen, both)
                for loen_period, loen in relations_to(adm, loen_units, related)
                if (both := loen_period.overlap(adm_period)) is not None
            ]
            if not loen_relations:
                day = adm_period.report_day(today)
                rows.append(
                    Chain(
                        source=source.on(day),
                        adm=Relation(unit=adm.on(day), period=adm_period),
                        loen=None,
                    )
                )
            for loen_period, loen, both in loen_relations:
                day = both.report_day(today)
                rows.append(
                    Chain(
                        source=source.on(day),
                        adm=Relation(unit=adm.on(day), period=adm_period),
                        loen=Relation(unit=loen.on(day), period=loen_period),
                    )
                )
    return sorted(
        rows,
        key=lambda row: (
            row.source.user_key,
            *relation_order(row.adm),
            *relation_order(row.loen),
        ),
    )


def to_csv(header: list[str], rows: Iterable[list[str]]) -> bytes:
    """A report as agreed with its receiver.

    UTF-8 without a byte order mark, `;` as separator, as names often have
    commas, every field quoted with `"` doubled inside (RFC 4180), and CRLF.
    """
    out = io.StringIO()
    writer = csv.writer(
        out, delimiter=";", quoting=csv.QUOTE_ALL, lineterminator="\r\n"
    )
    writer.writerow(header)
    writer.writerows(rows)
    return out.getvalue().encode("utf-8")


def relation_fields(system: str, relation: Relation | None) -> list[str]:
    """The System, Code, Name, From and To of a relation, or empty if none.

    From is its first day, and To its last, or empty if it does not end.
    """
    if relation is None:
        return ["", "", "", "", ""]
    last_day = relation.period.last_day
    return [
        system,
        relation.unit.user_key,
        relation.unit.name,
        relation.period.start.isoformat(),
        last_day.isoformat() if last_day is not None else "",
    ]


def loen_csv(adm_system: str, loen_system: str, rows: list[Chain]) -> bytes:
    return to_csv(
        [
            "Source_System",
            "Source_Code",
            "Source_Name",
            "Adm_System",
            "Adm_Code",
            "Adm_Name",
            "Adm_From",
            "Adm_To",
            "Target_System",
            "Target_Code",
            "Target_Name",
            "Target_From",
            "Target_To",
        ],
        (
            [
                SOR.title,
                row.source.user_key,
                row.source.name,
                *relation_fields(adm_system, row.adm),
                *relation_fields(loen_system, row.loen),
            ]
            for row in rows
        ),
    )


def report_file_prefix(name: str) -> str:
    """The start of a report's file names, sor_<name>_report_.

    `report` keeps it from matching a dump, whose name ends in a code system's
    name and the time.
    """
    return f"{SOR.name}_{name}_report_"


def report_file_name(name: str, time: datetime) -> str:
    """sor_<name>_report_<time>.csv, with a time such as 20261117_120000."""
    return f"{report_file_prefix(name)}{time:%Y%m%d_%H%M%S}.csv"


def period(start: datetime, end: datetime | None) -> Period:
    return Period(start=start.date(), end=end.date() if end is not None else None)


async def all_unit_histories(
    mo: GraphQLClient, roots: list[UUID]
) -> list[ListUnitHistoriesOrgUnitsObjects]:
    """The org units that are or were in the trees of the roots, from every page."""
    org_units = []
    cursor = None
    while True:
        page = await mo.list_unit_histories(roots, cursor)
        org_units.extend(page.objects)
        cursor = page.page_info.next_cursor
        if cursor is None:
            return org_units


async def all_relations(
    mo: GraphQLClient, roots: list[UUID]
) -> list[ListRelationsRelatedUnitsObjects]:
    """The relations to units that are or were in the trees of the roots."""
    relations = []
    cursor = None
    while True:
        page = await mo.list_relations(roots, cursor)
        relations.extend(page.objects)
        cursor = page.page_info.next_cursor
        if cursor is None:
            return relations


async def unit_histories(
    mo: GraphQLClient, roots: list[UUID]
) -> dict[UUID, UnitHistory]:
    """The units that are or were in the trees of the roots, with every period.

    A period with no days, such as of a unit terminated on the day it was made,
    is left out, and so is a unit with no other periods, as it was never active.
    """
    units = {}
    for org_unit in await all_unit_histories(mo, roots):
        periods = tuple(
            UnitPeriod(
                **period(v.validity.from_, v.validity.to).dict(),
                user_key=v.user_key,
                name=v.name,
            )
            for v in org_unit.validities
        )
        periods = tuple(p for p in periods if not p.empty)
        if periods:
            units[org_unit.uuid] = UnitHistory(uuid=org_unit.uuid, periods=periods)
    return units


def merged(periods: list[Period]) -> list[Period]:
    """The periods without empty ones, and with those that touch or overlap joined.

    MO splits a relation where the unit's other relations were set.
    """
    result: list[Period] = []
    for p in sorted(periods, key=lambda p: p.start):
        if p.empty:
            continue
        last = result[-1] if result else None
        if last is not None and (last.end is None or p.start <= last.end):
            end = None if last.end is None or p.end is None else max(last.end, p.end)
            result[-1] = Period(start=last.start, end=end)
        else:
            result.append(p)
    return result


async def relations(mo: GraphQLClient, roots: list[UUID]) -> Related:
    """The relations of the units in the trees of the roots, both ways, and when
    each was valid.
    """
    periods: defaultdict[tuple[UUID, UUID], list[Period]] = defaultdict(list)
    for relation in await all_relations(mo, roots):
        for v in relation.validities:
            when = period(v.validity.from_, v.validity.to)
            uuids = {org_unit.uuid for org_unit in v.org_units_response.objects}
            for uuid in uuids:
                for related_uuid in uuids - {uuid}:
                    periods[uuid, related_uuid].append(when)
    related: Related = defaultdict(list)
    for (uuid, related_uuid), unit_periods in periods.items():
        related[uuid].extend((when, related_uuid) for when in merged(unit_periods))
    return dict(related)


async def mo_roots(mo: GraphQLClient, code_system: CodeSystem) -> list[UUID]:
    """The units at the top of the code system's tree in MO.

    Its root unit, if it has one, else those found among MO's root units by their
    UUIDs, which are derived from their codes.

    Raises:
        RootNotFound: If it has no root unit, and no root in MO.
    """
    if code_system.root_unit is not None:
        return [code_system.root_unit.uuid]
    root_units = await mo.list_root_units()
    roots = [
        org_unit.uuid
        for org_unit in root_units.objects
        if any(
            code_system.org_unit_uuid(v.user_key) == org_unit.uuid
            for v in org_unit.validities
        )
    ]
    if not roots:
        raise RootNotFound(f"no root of {code_system.name} in MO")
    return roots


async def sor_units(mo: GraphQLClient) -> list[UnitHistory]:
    """Every unit of SOR in MO, also those that have ended or not started.

    Raises:
        RootNotFound: If SOR has no root in MO.
    """
    units = await unit_histories(mo, await mo_roots(mo, SOR))
    # By their UUIDs, which are derived from their codes. "Historiske enheder"
    # is not one of SOR's codes.
    return [
        unit
        for uuid, unit in units.items()
        if SOR.org_unit_uuid(unit.user_key) == uuid
        and unit.user_key != HISTORIC_USER_KEY
    ]


def root_name(units: dict[UUID, UnitHistory], root: UUID, today: date) -> str:
    """The name of a tree's root today, which names its system in the report.

    Raises:
        RootNotFound: If the root is not an active unit in MO.
    """
    root_unit = units[root].at(today) if root in units else None
    if root_unit is None:
        raise RootNotFound(f"root {root} is not an active unit in MO")
    return root_unit.name


async def last_report(mo: GraphQLClient, name: str) -> bytes | None:
    """The report's last file in the file store, or None if there is none.

    The last one MO wrote, rather than the newest name, as the time in the
    name repeats an hour when the clocks go back.
    """
    files = await mo.list_files(FileStore.EXPORTS)
    reports = [
        f for f in files.objects if f.file_name.startswith(report_file_prefix(name))
    ]
    if not reports:
        return None
    last = max(reports, key=attrgetter("updated_at"))
    read = await mo.read_file(FileStore.EXPORTS, last.file_name)
    return base64.b64decode(one(read.objects).base64_contents)


async def upload_report(
    report: LoenReportSettings,
    mo: GraphQLClient,
    dry_run: bool,
) -> Reported | None:
    """Upload the report, unless it is the same as its last one in the file store.

    `report` is the løn report's settings, which it is named after. Returns the
    report, or None if it did not change.

    Raises:
        RootNotFound: If SOR has no root in MO, or the Adm or løn root is not an
            active unit in MO.
    """
    now = datetime.now(tz=MO_TIMEZONE)
    today = now.date()
    sources = await sor_units(mo)
    adm_units = await unit_histories(mo, [report.root_adm])
    loen_units = await unit_histories(mo, [report.root_loen])
    adm_system = root_name(adm_units, report.root_adm, today)
    loen_system = root_name(loen_units, report.root_loen, today)
    # Every chain goes through an Adm unit, so their relations are all the
    # report needs
    related = await relations(mo, [report.root_adm])
    rows = loen_chains(sources, adm_units, loen_units, related, today)
    contents = loen_csv(adm_system, loen_system, rows)
    if await last_report(mo, report.name) == contents:
        return None

    file_name = report_file_name(report.name, now)
    reported = Reported(file_name=file_name, rows=len(rows))
    logger.info(
        "Uploading report", file_name=file_name, rows=len(rows), dry_run=dry_run
    )
    if dry_run:
        return reported
    await upload_file(mo, file_name, contents)
    return reported


@router.post("/report")
async def upload_reports(
    settings: depends.Settings,
    mo: depends.GraphQLClient,
    name: str | None = None,
    dry_run: bool = False,
) -> dict[str, Reported | None]:
    """Upload the løn report. `name`, if given, must be its name.

    A report the same as its last one is not uploaded, and is returned as None.
    One that cannot be made is logged, and the request fails. With `dry_run`,
    nothing is uploaded.
    """
    loen_report = settings.loen_report
    if (
        SOR.name not in settings.code_systems
        or loen_report is None
        or name not in (None, loen_report.name)
    ):
        raise HTTPException(status_code=404, detail="Report not configured")
    try:
        reported = await upload_report(loen_report, mo, dry_run=dry_run)
    except RootNotFound as e:
        logger.error("Not reported", report=loen_report.name, error=str(e))
        raise HTTPException(
            status_code=500, detail=f"Not reported: {loen_report.name}"
        ) from e
    return {loen_report.name: reported}
