"""The report of how the code systems' units link to a target tree.

In MO, a code system's unit is related to units of an administrative tree
(Adm), which are related to units of a target tree. The report has a row for each
such chain, code system unit -> Adm unit -> target unit, so it
is always clear which target unit belongs to which Adm unit. A chain that stops
early has empty fields for the rest.
"""

import csv
import io
from collections import defaultdict
from collections.abc import Sequence
from datetime import datetime
from operator import attrgetter
from uuid import UUID

import structlog
from fastapi import APIRouter
from fastapi import HTTPException
from pydantic import BaseModel

from mo_arbor import depends
from mo_arbor.autogenerated_graphql_client import GraphQLClient
from mo_arbor.autogenerated_graphql_client import ListRelatedUnitsOrgUnitsObjects
from mo_arbor.autogenerated_graphql_client import ListReportUnitsOrgUnitsObjects
from mo_arbor.code_system_file import HISTORIC_USER_KEY
from mo_arbor.code_system_file import InvalidFile
from mo_arbor.config import CodeSystem
from mo_arbor.config import CodeSystemName
from mo_arbor.config import ReportSettings
from mo_arbor.dumps import DumpNotFound
from mo_arbor.dumps import DumpStore
from mo_arbor.mo import MO_TIMEZONE
from mo_arbor.mo import upload_file

router = APIRouter()
logger = structlog.stdlib.get_logger()


class RootNotFound(Exception):
    pass


class ReportUnit(BaseModel, frozen=True):
    uuid: UUID
    user_key: str
    name: str


class Systems(BaseModel, frozen=True):
    """The names of the systems in the report, as their roots are named in MO."""

    source: str
    adm: str
    target: str


class Chain(BaseModel, frozen=True):
    """A row of the report, which may stop after its source or Adm unit."""

    source: ReportUnit
    adm: ReportUnit | None
    target: ReportUnit | None


class Reported(BaseModel, frozen=True):
    file_name: str
    rows: int


def by_user_key(units: list[ReportUnit]) -> list[ReportUnit]:
    return sorted(units, key=attrgetter("user_key"))


def chains(
    sources: list[ReportUnit],
    adm_units: dict[UUID, ReportUnit],
    target_units: dict[UUID, ReportUnit],
    related: dict[UUID, set[UUID]],
) -> list[Chain]:
    """The chains from each of the code system's units, the sources.

    `related` has each unit's related units. Sorted by code, so a report
    without changes is the same file, and is easy to read.
    """

    def linked(
        unit: ReportUnit | None, units: dict[UUID, ReportUnit]
    ) -> Sequence[ReportUnit | None]:
        """The unit's related units among `units`.

        [None] if there are none, or no unit, so the chain stops there and has
        None for the rest.
        """
        if unit is None:
            return [None]
        found = [units[r] for r in related.get(unit.uuid, ()) if r in units]
        return by_user_key(found) or [None]

    return [
        Chain(source=source, adm=adm, target=target)
        for source in by_user_key(sources)
        for adm in linked(source, adm_units)
        for target in linked(adm, target_units)
    ]


def to_csv(systems: Systems, rows: list[Chain]) -> bytes:
    """The report as agreed with its receiver.

    UTF-8 without a byte order mark, `;` as separator, as names often have
    commas, every field quoted with `"` doubled inside (RFC 4180), and CRLF.
    """
    out = io.StringIO()
    writer = csv.writer(
        out, delimiter=";", quoting=csv.QUOTE_ALL, lineterminator="\r\n"
    )
    writer.writerow(
        [
            "Source_System",
            "Source_Code",
            "Source_Name",
            "Adm_System",
            "Adm_Code",
            "Adm_Name",
            "Target_System",
            "Target_Code",
            "Target_Name",
        ]
    )
    for row in rows:
        source, adm, target = row.source, row.adm, row.target
        writer.writerow(
            [
                systems.source,
                source.user_key,
                source.name,
                systems.adm if adm else "",
                adm.user_key if adm else "",
                adm.name if adm else "",
                systems.target if target else "",
                target.user_key if target else "",
                target.name if target else "",
            ]
        )
    return out.getvalue().encode("utf-8")


def report_file_name(code_system: CodeSystem, time: datetime) -> str:
    """E.g. sor_relations_20261117_120000.csv.

    The code system's name comes first, so the file is not taken for one of
    its dumps, which end in the name and the time.
    """
    return f"{code_system.name}_relations_{time:%Y%m%d_%H%M%S}.csv"


async def all_report_units(
    mo: GraphQLClient, top_uuids: list[UUID]
) -> list[ListReportUnitsOrgUnitsObjects]:
    """The org units in the trees of the top units, from every page."""
    org_units = []
    cursor = None
    while True:
        page = await mo.list_report_units(top_uuids, cursor)
        org_units.extend(page.objects)
        cursor = page.page_info.next_cursor
        if cursor is None:
            return org_units


async def all_related_units(
    mo: GraphQLClient, root: UUID
) -> list[ListRelatedUnitsOrgUnitsObjects]:
    """The org units in the tree of the root, with their relations, from every page."""
    org_units = []
    cursor = None
    while True:
        page = await mo.list_related_units(root, cursor)
        org_units.extend(page.objects)
        cursor = page.page_info.next_cursor
        if cursor is None:
            return org_units


async def report_units_in_trees(
    mo: GraphQLClient, top_uuids: list[UUID]
) -> dict[UUID, ReportUnit]:
    """The units active now in the trees of the top units."""
    return {
        org_unit.uuid: ReportUnit(
            uuid=org_unit.uuid,
            user_key=org_unit.current.user_key,
            name=org_unit.current.name,
        )
        for org_unit in await all_report_units(mo, top_uuids)
        if org_unit.current is not None
    }


async def adm_units_and_relations(
    mo: GraphQLClient, root: UUID
) -> tuple[dict[UUID, ReportUnit], dict[UUID, set[UUID]]]:
    """The Adm units active now, and the units each unit is related to.

    Every chain goes through an Adm unit, so their relations are all the
    report needs. A relation goes both ways.
    """
    # Only units and relations active now, as MO returns by default, have a
    # current
    active = [
        (o.uuid, o.current) for o in await all_related_units(mo, root) if o.current
    ]
    units = {
        uuid: ReportUnit(uuid=uuid, user_key=current.user_key, name=current.name)
        for uuid, current in active
    }
    related: dict[UUID, set[UUID]] = defaultdict(set)
    for uuid, current in active:
        others = {
            other.uuid
            for relation in current.related_units_response.objects
            if relation.current
            for other in relation.current.org_units_response.objects
        } - {uuid}
        for other in others:
            related[uuid].add(other)
            related[other].add(uuid)
    return units, dict(related)


async def code_system_units(
    mo: GraphQLClient, code_system: CodeSystem, store: DumpStore
) -> list[ReportUnit]:
    """The code system's units active now in MO.

    They are found as the ingest finds them, under the code system's top
    units, whose UUIDs are derived from their codes. "Historiske enheder" is
    not one of the code system's codes, so it is left out.

    Raises:
        DumpNotFound: If there are no dumps, which have the roots.
        InvalidFile: If the newest dump is invalid.
    """
    dump = await store.load_newest(mo)
    units = await report_units_in_trees(mo, code_system.top_uuids(dump.units))
    return [
        unit
        for uuid, unit in units.items()
        if code_system.org_unit_uuid(unit.user_key) == uuid
        and unit.user_key != HISTORIC_USER_KEY
    ]


def root_name(units: dict[UUID, ReportUnit], root: UUID) -> str:
    """The name of a tree's root, which names its system in the report.

    Raises:
        RootNotFound: If the root is not among the units, those active now.
    """
    if root not in units:
        raise RootNotFound(f"root {root} is not an active unit in MO")
    return units[root].name


async def report_code_system(
    code_system: CodeSystem,
    mo: GraphQLClient,
    store: DumpStore,
    report_settings: ReportSettings,
    dry_run: bool,
) -> Reported:
    """Upload a report of the code system's relations.

    Raises:
        DumpNotFound: If there are no dumps, which have the roots.
        InvalidFile: If the newest dump is invalid.
        RootNotFound: If the Adm or target root is not an active unit in MO.
    """
    log = logger.bind(code_system=code_system.name)
    sources = await code_system_units(mo, code_system, store)
    adm_units, related = await adm_units_and_relations(mo, report_settings.root_adm)
    target_units = await report_units_in_trees(mo, [report_settings.root_target])
    systems = Systems(
        # Which is also the name of its root in MO
        source=code_system.title,
        adm=root_name(adm_units, report_settings.root_adm),
        target=root_name(target_units, report_settings.root_target),
    )
    rows = chains(sources, adm_units, target_units, related)
    contents = to_csv(systems, rows)
    file_name = report_file_name(code_system, datetime.now(tz=MO_TIMEZONE))
    reported = Reported(file_name=file_name, rows=len(rows))
    log.info("Uploading report", file_name=file_name, rows=len(rows), dry_run=dry_run)
    if dry_run:
        return reported
    await upload_file(mo, file_name, contents)
    return reported


@router.post("/report")
async def report(
    settings: depends.Settings,
    mo: depends.GraphQLClient,
    dump_stores: depends.DumpStores,
    code_system: CodeSystemName | None = None,
    dry_run: bool = False,
) -> dict[str, Reported]:
    """Upload a report of how each code system's units link to a target tree.

    Reports every code system in `CODE_SYSTEMS`, or only the one named by
    `code_system`.

    A code system is not reported if its dumps are missing or the newest is
    invalid, as the roots of SOR's tree come from it, or if the Adm or target root
    is not an active unit in MO. This is logged as an error, and the request
    fails after the other code systems are reported.

    With `dry_run`, returns what would be uploaded without uploading it.
    """
    if settings.report is None:
        raise HTTPException(status_code=404, detail="Report not configured")
    if code_system is None:
        names = settings.code_systems
    elif code_system in settings.code_systems:
        names = {code_system}
    else:
        raise HTTPException(status_code=404, detail="Code system not configured")

    results: dict[str, Reported] = {}
    failed = []
    for name in names:
        try:
            results[name] = await report_code_system(
                CodeSystem(name=name),
                mo,
                dump_stores[name],
                settings.report,
                dry_run=dry_run,
            )
        except (DumpNotFound, InvalidFile, RootNotFound) as e:
            logger.error("Not reported", code_system=name, error=str(e))
            failed.append(name)
    if failed:
        raise HTTPException(
            status_code=500, detail=f"Not reported: {', '.join(failed)}"
        )
    return results
