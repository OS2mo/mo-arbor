MO_TIMEZONE = ZoneInfo("Europe/Copenhagen")


class ClassNotFound(Exception):
    pass


def mo_datetime(d: date) -> datetime:
    """Start of the day in MO's time zone."""
    return datetime.combine(d, time.min, tzinfo=MO_TIMEZONE)


def unit_end(period_ends: set[datetime | None]) -> date | None:
    """The end of a unit in MO, from the ends of its periods; None if open-ended.

    The current period ends where the next one starts, such as at a name
    change planned for later. The unit ends where its last period does.
    """
    if None in period_ends:
        return None
    # Only for mypy, which does not see that no end is None here
    return max(end.date() for end in period_ends if end is not None)


async def get_class(mo: GraphQLClient, facet: str, user_key: str) -> UUID:
    classes = await mo.get_class(facet, user_key)
    not_found = ClassNotFound(f"no {facet} class with user_key {user_key!r}")
    return one(classes.objects, too_short=not_found).uuid


async def check_classes(mo: GraphQLClient, units: Collection[Unit]) -> None:
    """Check that MO has the type and level classes of every unit.

    The event handler looks them up, so without one, the unit and every unit
    under it would be left out of MO until someone makes the class.

    Raises:
        ClassNotFound: Naming every class MO does not have.
    """
    wanted = {
        "org_unit_type": {unit.org_unit_type for unit in units},
        "org_unit_level": {
            unit.org_unit_level for unit in units if unit.org_unit_level is not None
        },
    }
    missing = []
    for facet, user_keys in wanted.items():
        classes = await mo.list_classes(facet, list(user_keys))
        found = {v.user_key for c in classes.objects for v in c.validities}
        if user_keys - found:
            names = ", ".join(sorted(user_keys - found))
            missing.append(f"no {facet} classes {names}")
    if missing:
        raise ClassNotFound("; ".join(missing))


def depths(parents: dict[UUID, UUID | None]) -> dict[UUID, int]:
    """Each unit's depth, where a unit whose parent is not among them is 1."""

    @cache
    def depth(uuid: UUID) -> int:
        parent = parents[uuid]
        if parent not in parents:
            return 1
        return depth(parent) + 1

    return {uuid: depth(uuid) for uuid in parents}


async def org_units_in_trees(
    mo: GraphQLClient, top_uuids: list[UUID], from_date: datetime
) -> list[ListOrgUnitsOrgUnitsObjects]:
    """The org units in the trees of the top units, active from the date."""
    org_units = []
    cursor = None
    while True:
        page = await mo.list_org_units(top_uuids, from_date, cursor)
        org_units.extend(page.objects)
        cursor = page.page_info.next_cursor
        if cursor is None:
            return org_units


def code_system_depths(
    code_system: CodeSystem, org_units: list[ListOrgUnitsOrgUnitsObjects]
) -> dict[str, int]:
    """The code system's units among the org units, by user_key, with depths.

    A unit is the code system's if its UUID is the one derived from its
    user_key, and it is not the root unit.
    """
    root_unit_uuid = code_system.root_unit.uuid if code_system.root_unit else None
    user_keys: dict[UUID, str] = {}
    parents: dict[UUID, UUID | None] = {}
    for org_unit in org_units:
        # The period at the date they were read from, or the first after it.
        # MO does not promise their order.
        first = min(org_unit.validities, key=lambda v: v.validity.from_)
        if org_unit.uuid == root_unit_uuid:
            continue
        if code_system.org_unit_uuid(first.user_key) != org_unit.uuid:
            continue
        user_keys[org_unit.uuid] = first.user_key
        parent = first.parent_response
        parents[org_unit.uuid] = parent.uuid if parent else None
    return {user_keys[uuid]: depth for uuid, depth in depths(parents).items()}


async def units_in_mo(
    mo: GraphQLClient, code_system: CodeSystem, dump: Dump
) -> dict[str, int]:
    """The code system's units active in MO from the dump's date, with depths.

    They are the units under the code system's root unit, or under the dump's
    roots if it has none.
    """
    org_units = await org_units_in_trees(
        mo, code_system.top_uuids(dump.units), mo_datetime(dump.date)
    )
    return code_system_depths(code_system, org_units)


async def create_root_unit(mo: GraphQLClient, code_system: CodeSystem) -> None:
    """Make the unit the code system's roots go under, unless MO has it.

    Raises:
        ClassNotFound: If MO has no class for its type.
    """
    root_unit = code_system.root_unit
    if root_unit is None:
        return
    if (await mo.get_org_unit(root_unit.uuid)).objects:
        return
    await mo.create_org_unit(
        OrganisationUnitCreateInput(
            uuid=root_unit.uuid,
            user_key=root_unit.user_key,
            name=root_unit.name,
            org_unit_type=await get_class(
                mo, "org_unit_type", root_unit.org_unit_type_user_key
            ),
            validity=RAValidityInput(from_=mo_datetime(root_unit.validity_from)),
        )
    )


async def upload_file(mo: GraphQLClient, file_name: str, contents: bytes) -> None:
    """Upload a file to MO's EXPORTS file store.

    The codegen client cannot send the multipart request that `upload_file`
    requires, so this is done by hand, with the client's authenticated HTTP
    client. A file with the same name is not overwritten.

    Raises:
        GraphQLClientGraphQLMultiError: If MO refuses the file.
    """
    query = (
        "mutation($file: Upload!) "
        "{ upload_file(file_store: EXPORTS, file: $file, force: false) }"
    )
    r = await mo.http_client.post(
        mo.url,
        data={
            "operations": json.dumps({"query": query, "variables": {"file": None}}),
            "map": json.dumps({"file": ["variables.file"]}),
        },
        files={"file": (file_name, contents)},
    )
    r.raise_for_status()
    body = r.json()
    if body.get("errors"):
        raise GraphQLClientGraphQLMultiError.from_errors_dicts(
            body["errors"], body.get("data") or {}
        )
