"""Helpers for reading and writing MO."""

from datetime import date
from datetime import datetime
from datetime import time
from uuid import UUID
from zoneinfo import ZoneInfo

from more_itertools import one

from mo_arbor.autogenerated_graphql_client import GraphQLClient
from mo_arbor.autogenerated_graphql_client import OrganisationUnitCreateInput
from mo_arbor.autogenerated_graphql_client import RAValidityInput
from mo_arbor.config import CodeSystem

MO_TIMEZONE = ZoneInfo("Europe/Copenhagen")


class ClassNotFound(Exception):
    pass


def mo_datetime(d: date) -> datetime:
    """Start of the day in MO's time zone."""
    return datetime.combine(d, time.min, tzinfo=MO_TIMEZONE)


def unit_end(period_ends: set[datetime | None]) -> date | None:
    """The end of a unit in MO, from the ends of its periods; None if open-ended.

    The current period ends where the next one starts, such as at a name
    change planned for later. The unit ends where its last period does.
    """
    if None in period_ends:
        return None
    # Only for mypy, which does not see that no end is None here
    return max(end.date() for end in period_ends if end is not None)


async def get_class(mo: GraphQLClient, facet: str, user_key: str) -> UUID:
    classes = await mo.get_class(facet, user_key)
    not_found = ClassNotFound(f"no {facet} class with user_key {user_key!r}")
    return one(classes.objects, too_short=not_found).uuid


async def create_root_unit(mo: GraphQLClient, code_system: CodeSystem) -> None:
    """Make the unit the code system's roots go under, unless MO has it.

    Raises:
        ClassNotFound: If MO has no class for its type.
    """
    root_unit = code_system.root_unit
    if root_unit is None:
        return
    if (await mo.get_org_unit(root_unit.uuid)).objects:
        return
    await mo.create_org_unit(
        OrganisationUnitCreateInput(
            uuid=root_unit.uuid,
            user_key=root_unit.user_key,
            name=root_unit.name,
            org_unit_type=await get_class(
                mo, "org_unit_type", root_unit.org_unit_type_user_key
            ),
            validity=RAValidityInput(from_=mo_datetime(root_unit.validity_from)),
        )
    )
