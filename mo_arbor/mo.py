"""Helpers for reading and writing MO."""

from datetime import date
from datetime import datetime
from datetime import time
from uuid import UUID
from zoneinfo import ZoneInfo

from more_itertools import one

from mo_arbor.autogenerated_graphql_client import GraphQLClient
from mo_arbor.autogenerated_graphql_client import OrganisationUnitCreateInput
from mo_arbor.autogenerated_graphql_client import RAValidityInput
from mo_arbor.config import CodeSystem
from mo_arbor.dumps import Dump

MO_TIMEZONE = ZoneInfo("Europe/Copenhagen")


class ClassNotFound(Exception):
    pass


def mo_datetime(d: date) -> datetime:
    """Start of the day in MO's time zone."""
    return datetime.combine(d, time.min, tzinfo=MO_TIMEZONE)


def unit_end(period_ends: set[datetime | None]) -> date | None:
    """The end of a unit in MO, from the ends of its periods; None if open-ended.

    The current period ends where the next one starts, such as at a name
    change planned for later. The unit ends where its last period does.
    """
    if None in period_ends:
        return None
    # Only for mypy, which does not see that no end is None here
    return max(end.date() for end in period_ends if end is not None)


async def get_class(mo: GraphQLClient, facet: str, user_key: str) -> UUID:
    classes = await mo.get_class(facet, user_key)
    not_found = ClassNotFound(f"no {facet} class with user_key {user_key!r}")
    return one(classes.objects, too_short=not_found).uuid


def depths(parents: dict[UUID, UUID | None]) -> dict[UUID, int]:
    """Each unit's depth, where a unit whose parent is not among them is 1."""
    by_uuid = {}
    for uuid, parent in parents.items():
        depth = 1
        above = parent
        while above in parents:
            depth += 1
            above = parents[above]
        by_uuid[uuid] = depth
    return by_uuid


async def units_in_mo(
    mo: GraphQLClient, code_system: CodeSystem, dump: Dump
) -> dict[str, int]:
    """The code system's units active in MO from the dump's date, with depths.

    They are the units under the code system's root unit, or under the dump's
    roots if it has none. Of those, a unit is the code system's if its UUID is
    the one derived from its user_key, and it is not the root unit.
    """
    root_unit_uuid = None
    if code_system.root_unit is not None:
        root_unit_uuid = code_system.root_unit.uuid
        roots = [root_unit_uuid]
    else:
        roots = [
            code_system.org_unit_uuid(user_key)
            for user_key, unit in dump.units.items()
            if unit.parent is None
        ]
    user_keys: dict[UUID, str] = {}
    parents: dict[UUID, UUID | None] = {}
    cursor = None
    while True:
        page = await mo.list_org_units(roots, mo_datetime(dump.date), cursor)
        for org_unit in page.objects:
            # The period at the dump's date, or the first after it. MO returns
            # them in the order they were registered, not by their start.
            first = min(org_unit.validities, key=lambda v: v.validity.from_)
            if org_unit.uuid == root_unit_uuid:
                continue
            if code_system.org_unit_uuid(first.user_key) != org_unit.uuid:
                continue
            user_keys[org_unit.uuid] = first.user_key
            parent = first.parent_response
            parents[org_unit.uuid] = parent.uuid if parent else None
        cursor = page.page_info.next_cursor
        if cursor is None:
            break
    return {user_keys[uuid]: depth for uuid, depth in depths(parents).items()}


async def create_root_unit(mo: GraphQLClient, code_system: CodeSystem) -> None:
    """Make the unit the code system's roots go under, unless MO has it.

    Raises:
        ClassNotFound: If MO has no class for its type.
    """
    root_unit = code_system.root_unit
    if root_unit is None:
        return
    if (await mo.get_org_unit(root_unit.uuid)).objects:
        return
    await mo.create_org_unit(
        OrganisationUnitCreateInput(
            uuid=root_unit.uuid,
            user_key=root_unit.user_key,
            name=root_unit.name,
            org_unit_type=await get_class(
                mo, "org_unit_type", root_unit.org_unit_type_user_key
            ),
            validity=RAValidityInput(from_=mo_datetime(root_unit.validity_from)),
        )
    )
