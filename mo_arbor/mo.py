"""Helpers for reading and writing MO."""

from datetime import date
from datetime import datetime
from datetime import time
from uuid import UUID
from zoneinfo import ZoneInfo

from more_itertools import one

from mo_arbor.autogenerated_graphql_client import GraphQLClient


class ClassNotFound(Exception):
    pass


def mo_datetime(d: date) -> datetime:
    """Start of the day in MO's time zone."""
    return datetime.combine(d, time.min, tzinfo=ZoneInfo("Europe/Copenhagen"))


async def get_class(mo: GraphQLClient, facet: str, user_key: str) -> UUID:
    classes = await mo.get_class(facet, user_key)
    not_found = ClassNotFound(f"no {facet} class with user_key {user_key!r}")
    return one(classes.objects, too_short=not_found).uuid
