import logging

from fastapi import FastAPI
from fastramqpi.events import GraphQLEvents
from fastramqpi.events import Listener
from fastramqpi.events import Namespace
from fastramqpi.main import FastRAMQPI

from mo_arbor import events
from mo_arbor import ingest
from mo_arbor.autogenerated_graphql_client import GraphQLClient
from mo_arbor.config import CodeSystem
from mo_arbor.config import Settings
from mo_arbor.database import Base
from mo_arbor.dumps import DumpStore

GRAPHQL_VERSION = 30


def create_app() -> FastAPI:
    settings = Settings()

    fastramqpi = FastRAMQPI(
        application_name="mo-arbor",
        settings=settings.fastramqpi,
        graphql_version=GRAPHQL_VERSION,
        graphql_client_cls=GraphQLClient,
        graphql_events=GraphQLEvents(
            declare_namespaces=[Namespace(name=name) for name in settings.code_systems],
            declare_listeners=[
                Listener(
                    namespace=name,
                    user_key=f"{name}_org_unit",
                    routing_key="org_unit",
                    path=f"/{name}/org_unit",
                    parallelism=10,
                )
                for name in settings.code_systems
            ],
        ),
        database_metadata=Base.metadata,
    )
    fastramqpi.add_context(settings=settings)
    fastramqpi.add_context(
        dump_stores={
            name: DumpStore(name, CodeSystem(name=name).rows_model)
            for name in settings.code_systems
        }
    )

    app = fastramqpi.get_app()
    app.include_router(events.router)
    app.include_router(ingest.router)

    logging.getLogger("httpx").setLevel(logging.WARNING)

    return app
