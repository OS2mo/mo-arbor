"""The whole integration: a dump, ingest, MO's event system and our handler.

The other tests stop at the events ingest sends, or post an event straight to
the handler. Here, MO hands ingest's events to the integration's own listener.
"""

import pytest
from fastramqpi.pytest_util import retry
from httpx import AsyncClient
from more_itertools import one

from mo_arbor.autogenerated_graphql_client import GraphQLClient
from mo_arbor.config import CodeSystem
from tests.helpers import UploadFile
from tests.helpers import file
from tests.helpers import row

# Made-up codes in the shape of real ones, with valid check digits
ROOT = "1001000016005"
CHILD = "100001000016006"

MARCH_31 = "region_sor_20260331_120000.csv"


@pytest.mark.integration_test
@pytest.mark.usefixtures("region", "klinisk_enhed", "n1")
async def test_ingested_units_reach_mo(
    test_client: AsyncClient,
    graphql_client: GraphQLClient,
    upload_file: UploadFile,
    sor: CodeSystem,
) -> None:
    root = row(ROOT, name="Root", org_unit_type="region")
    child = row(CHILD, parent=ROOT, name="Afdeling")
    await upload_file(MARCH_31, file(root, child))

    r = await test_client.post("/ingest", params={"code_system": "sor"})
    r.raise_for_status()

    @retry()
    async def verify_units() -> None:
        r = await graphql_client.get_org_unit(sor.org_unit_uuid(CHILD))
        current = one(r.objects).current
        assert current is not None
        assert current.name == "Afdeling"
        assert current.parent_response is not None
        assert current.parent_response.uuid == sor.org_unit_uuid(ROOT)

    await verify_units()
