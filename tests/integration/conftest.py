@pytest.fixture
def upload_file(mo_client: AsyncClient) -> UploadFile:
    """Upload a file to MO's EXPORTS file store, overwriting any existing one.

    The file is encoded as the supplier's are, as UTF-8 with a byte order mark.
    The codegen client cannot send the multipart request that `upload_file`
    requires, so this is done by hand, as in OS2mo's own tests.
    """

    async def upload(file_name: str, contents: str) -> None:
        query = (
            "mutation($file: Upload!) "
            "{ upload_file(file_store: EXPORTS, file: $file, force: true) }"
        )
        r = await mo_client.post(
            f"/graphql/v{GRAPHQL_VERSION}",
            data={
                "operations": json.dumps({"query": query, "variables": {"file": None}}),
                "map": json.dumps({"file": ["variables.file"]}),
            },
            files={"file": (file_name, contents.encode("utf-8-sig"))},
        )
        r.raise_for_status()
        assert "errors" not in r.json(), r.json()

    return upload


