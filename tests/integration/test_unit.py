@pytest.mark.integration_test
async def test_code_systems_are_separate_trees(
    test_client: AsyncClient,
    graphql_client: GraphQLClient,
    upload_file: UploadFile,
    classes: Classes,
) -> None:
    """The same user_key in two code systems is two units."""
    await upload_file(MARCH_31, file(row("1001000016005", org_unit_type="region")))
    await upload_file(
        "region_okosted_20260331_120000.csv",
        file(row("1001000016005", name="Økosted", org_unit_type="økosted")),
    )

    await handle_all(test_client, "1001000016005", code_system="sor")
    await handle_all(test_client, "1001000016005", code_system="okosted")

    r = await graphql_client.get_org_unit(OKOSTED.uuid("1001000016005"))
    current = r.objects[0].current
    assert current is not None
    assert current.name == "Økosted"
    assert current.unit_type is not None
    assert current.unit_type.uuid == classes["økosted"]
    assert await history(graphql_client, SOR.uuid("1001000016005")) == [
        ("Unit", date(2015, 7, 30), None)
    ]


