# As in CODE_SYSTEMS in CI
SOR = CodeSystem(
    name="sor", file_pattern="region_sor_%Y%m%d_%H%M%S.csv", uuid_namespace="sor.dk"
)
OKOSTED = CodeSystem(
    name="okosted",
    file_pattern="region_okosted_%Y%m%d_%H%M%S.csv",
    uuid_namespace="okosted",
)

# Made-up codes in the shape of real ones, with valid check digits
ROOT = "1001000016005"
CHILD = "100001000016006"

MARCH_31 = "region_sor_20260331_120000.csv"
APRIL_1 = "region_sor_20260401_120000.csv"
APRIL_2 = "region_sor_20260402_120000.csv"

SEED_VALIDITY = ValidityInput(from_=mo_datetime(date(1930, 1, 1)))

Classes = dict[str, UUID]


@pytest.fixture
async def classes(graphql_client: GraphQLClient) -> Classes:
    """The classes the dumps below use, by user_key."""
    facets = {
        "org_unit_type": ["region", "klinisk enhed", "økosted"],
        "org_unit_level": ["N1", "N2"],
    }
    classes = {}
    for facet, user_keys in facets.items():
        r = await graphql_client.create_facet(
            FacetCreateInput(user_key=facet, validity=SEED_VALIDITY)
        )
        for user_key in user_keys:
            c = await graphql_client.create_class(
                ClassCreateInput(
                    user_key=user_key,
                    name=user_key,
                    facet_uuid=r.uuid,
                    validity=SEED_VALIDITY,
                )
            )
            classes[user_key] = c.uuid
    return classes


def tree(child_name: str = "Afdeling", child_to: str = "") -> str:
    return file(
        row(ROOT, name="Root", org_unit_type="region"),
        row(
            CHILD,
            parent=ROOT,
            validity_from="2020-01-01",
            validity_to=child_to,
            name=child_name,
        ),
    )


async def handle(
    test_client: AsyncClient, user_key: str, code_system: str = "sor"
) -> Response:
    return await test_client.post(
        f"/{code_system}/org_unit",
        json=jsonable_encoder(Event(subject=user_key, priority=1)),
    )


async def handle_all(
    test_client: AsyncClient, *user_keys: str, code_system: str = "sor"
) -> None:
    for user_key in user_keys:
        r = await handle(test_client, user_key, code_system)
        r.raise_for_status()


async def history(
    graphql_client: GraphQLClient, uuid: UUID
) -> list[tuple[str, date, date | None]]:
    """Name and validity of each period of the unit, oldest first.

    MO's end dates are exclusive: a period ending 2026-04-01 has 31 March as
    its last day.
    """
    r = await graphql_client.get_org_unit_history(uuid)
    if not r.objects:
        return []
    return [
        (
            v.name,
            v.validity.from_.date(),
            v.validity.to.date() if v.validity.to else None,
        )
        for v in r.objects[0].validities
    ]


def span(periods: list[tuple[str, date, date | None]]) -> tuple[date, date | None]:
    """Start and end of periods that follow each other without a gap."""
    assert all(a[2] == b[1] for a, b in pairwise(periods))
    return periods[0][1], periods[-1][2]


@pytest.mark.integration_test
async def test_unit_is_created(
    test_client: AsyncClient,
    graphql_client: GraphQLClient,
    upload_file: UploadFile,
    classes: Classes,
) -> None:
    await upload_file(MARCH_31, tree())

    await handle_all(test_client, ROOT, CHILD)

    r = await graphql_client.get_org_unit(SOR.uuid(CHILD))
    current = r.objects[0].current
    assert current is not None
    assert current.user_key == CHILD
    assert current.name == "Afdeling"
    assert current.parent is not None
    assert current.parent.uuid == SOR.uuid(ROOT)
    assert current.unit_type is not None
    assert current.unit_type.uuid == classes["klinisk enhed"]
    assert current.org_unit_level is not None
    assert current.org_unit_level.uuid == classes["N1"]
    # A new unit starts at its validity_from
    assert await history(graphql_client, SOR.uuid(CHILD)) == [
        ("Afdeling", date(2020, 1, 1), None)
    ]
    # The root is at the top of MO's tree
    r = await graphql_client.get_org_unit(SOR.uuid(ROOT))
    current = r.objects[0].current
    assert current is not None
    assert current.parent is None


