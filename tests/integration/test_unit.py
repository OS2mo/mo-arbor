# Made-up codes in the shape of real ones, with valid check digits
ROOT = "1001000016005"
CHILD = "100001000016006"

MARCH_31 = "region_sor_20260331_120000.csv"
APRIL_1 = "region_sor_20260401_120000.csv"
OKOSTED_MARCH_31 = "region_okosted_20260331_120000.csv"


@pytest.fixture
def trigger_org_unit(
    test_client: AsyncClient,
) -> Callable[[CodeSystem, str], Awaitable[Response]]:
    """Send the code system's handler an event for the user_key."""

    async def inner(code_system: CodeSystem, user_key: str) -> Response:
        return await test_client.post(
            f"/{code_system.name}/org_unit",
            json=jsonable_encoder(Event(subject=user_key, priority=1)),
        )

    return inner


@pytest.fixture
def trigger_org_units(
    trigger_org_unit: Callable[[CodeSystem, str], Awaitable[Response]],
) -> Callable[[CodeSystem, list[str]], Awaitable[None]]:
    """Trigger each user_key's event in turn, failing if one fails."""

    async def inner(code_system: CodeSystem, user_keys: list[str]) -> None:
        for user_key in user_keys:
            r = await trigger_org_unit(code_system, user_key)
            r.raise_for_status()

    return inner


async def history(
    graphql_client: GraphQLClient, uuid: UUID
) -> list[tuple[str, date, date | None]]:
    """Name and validity of each period of the unit, oldest first.

    MO's end dates are exclusive: a period ending 2026-04-01 has 31 March as
    its last day.
    """
    r = await graphql_client._testing__get_org_unit_history(uuid)
    org_unit = only(r.objects)
    if org_unit is None:
        return []
    return [
        (
            v.name,
            v.validity.from_.date(),
            v.validity.to.date() if v.validity.to else None,
        )
        for v in org_unit.validities
    ]


@pytest.mark.integration_test
@pytest.mark.usefixtures("region")
async def test_unit_is_created(
    trigger_org_units: Callable[[CodeSystem, list[str]], Awaitable[None]],
    graphql_client: GraphQLClient,
    upload_file: UploadFile,
    sor: CodeSystem,
    klinisk_enhed: UUID,
    n1: UUID,
) -> None:
    root = row(ROOT, name="Root", org_unit_type="region")
    child = row(CHILD, parent=ROOT, name="Afdeling", validity_from="2020-01-01")
    await upload_file(MARCH_31, file(root, child))

    await trigger_org_units(sor, [ROOT, CHILD])

    r = await graphql_client.get_org_unit(sor.org_unit_uuid(CHILD))
    current = one(r.objects).current
    assert current is not None
    assert current.user_key == CHILD
    assert current.name == "Afdeling"
    assert current.parent_response is not None
    assert current.parent_response.uuid == sor.org_unit_uuid(ROOT)
    assert current.unit_type_response is not None
    assert current.unit_type_response.uuid == klinisk_enhed
    assert current.unit_level_response is not None
    assert current.unit_level_response.uuid == n1
    # A new unit starts at its validity_from
    assert await history(graphql_client, sor.org_unit_uuid(CHILD)) == [
        ("Afdeling", date(2020, 1, 1), None)
    ]
    # The root is at the top of MO's tree
    r = await graphql_client.get_org_unit(sor.org_unit_uuid(ROOT))
    current = one(r.objects).current
    assert current is not None
    assert current.parent_response is None


@pytest.mark.integration_test
@pytest.mark.usefixtures("region", "n1")
async def test_code_systems_are_separate_trees(
    trigger_org_units: Callable[[CodeSystem, list[str]], Awaitable[None]],
    graphql_client: GraphQLClient,
    upload_file: UploadFile,
    sor: CodeSystem,
    okosted: CodeSystem,
    juridisk_enhed: UUID,
) -> None:
    """The same user_key in two code systems is two units."""
    sor_root = row(ROOT, name="Root", org_unit_type="region")
    okosted_root = row(ROOT, name="Økosted", org_unit_type="juridisk enhed")
    await upload_file(MARCH_31, file(sor_root))
    await upload_file(OKOSTED_MARCH_31, file(okosted_root))

    await trigger_org_units(sor, [ROOT])
    await trigger_org_units(okosted, [ROOT])

    r = await graphql_client.get_org_unit(okosted.org_unit_uuid(ROOT))
    current = one(r.objects).current
    assert current is not None
    assert current.name == "Økosted"
    assert current.unit_type_response is not None
    assert current.unit_type_response.uuid == juridisk_enhed
    r = await graphql_client.get_org_unit(sor.org_unit_uuid(ROOT))
    current = one(r.objects).current
    assert current is not None
    assert current.name == "Root"


@pytest.mark.integration_test
@pytest.mark.usefixtures("region", "klinisk_enhed", "n1")
async def test_unit_is_created_with_its_end(
    trigger_org_units: Callable[[CodeSystem, list[str]], Awaitable[None]],
    graphql_client: GraphQLClient,
    upload_file: UploadFile,
    sor: CodeSystem,
) -> None:
    root = row(ROOT, name="Root", org_unit_type="region")
    child = row(
        CHILD,
        parent=ROOT,
        name="Afdeling",
        validity_from="2020-01-01",
        validity_to="2030-12-31",
    )
    await upload_file(MARCH_31, file(root, child))

    await trigger_org_units(sor, [ROOT, CHILD])

    # Ends the day after its validity_to, its last day
    assert await history(graphql_client, sor.org_unit_uuid(CHILD)) == [
        ("Afdeling", date(2020, 1, 1), date(2031, 1, 1))
    ]


@pytest.mark.integration_test
@pytest.mark.usefixtures("region", "klinisk_enhed", "n1")
async def test_newest_dump_is_read(
    trigger_org_units: Callable[[CodeSystem, list[str]], Awaitable[None]],
    graphql_client: GraphQLClient,
    upload_file: UploadFile,
    sor: CodeSystem,
) -> None:
    """An event sent for an older dump does not write its outdated data."""
    root = row(ROOT, name="Root", org_unit_type="region")
    child = row(CHILD, parent=ROOT, name="Old", validity_from="2020-01-01")
    await upload_file(MARCH_31, file(root, child))
    child = row(CHILD, parent=ROOT, name="New", validity_from="2020-01-01")
    await upload_file(APRIL_1, file(root, child))

    await trigger_org_units(sor, [ROOT, CHILD])

    assert await history(graphql_client, sor.org_unit_uuid(CHILD)) == [
        ("New", date(2020, 1, 1), None)
    ]


@pytest.mark.integration_test
@pytest.mark.usefixtures("region", "n1")
async def test_unknown_class_fails(
    trigger_org_units: Callable[[CodeSystem, list[str]], Awaitable[None]],
    trigger_org_unit: Callable[[CodeSystem, str], Awaitable[Response]],
    graphql_client: GraphQLClient,
    upload_file: UploadFile,
    sor: CodeSystem,
) -> None:
    """The event is retried until someone creates the class."""
    root = row(ROOT, name="Root", org_unit_type="region")
    child = row(CHILD, parent=ROOT, org_unit_type="x")
    await upload_file(MARCH_31, file(root, child))
    await trigger_org_units(sor, [ROOT])

    r = await trigger_org_unit(sor, CHILD)

    assert r.status_code == 500
    assert await history(graphql_client, sor.org_unit_uuid(CHILD)) == []


