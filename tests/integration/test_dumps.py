from datetime import UTC
from datetime import date
from datetime import datetime

import pytest

from mo_arbor.autogenerated_graphql_client import GraphQLClient
from mo_arbor.code_system_file import InvalidFile
from mo_arbor.dumps import DumpFile
from mo_arbor.dumps import DumpNotFound
from mo_arbor.dumps import DumpStore
from tests.helpers import UploadFile
from tests.helpers import file
from tests.helpers import row

VALID = file(row("R"))
VALID_WITH_CHILD = file(row("R"), row("C", parent="R"))
# The same code twice
INVALID = file(row("R"), row("R"))

APRIL_30 = "region_sor_20260430_120000.csv"
MAY_1_MORNING = "region_sor_20260501_080000.csv"
MAY_1_EVENING = "region_sor_20260501_200000.csv"
OTHER_APRIL_30 = "region_other_20260430_120000.csv"
OTHER_MAY_1 = "region_other_20260501_120000.csv"


@pytest.mark.integration_test
async def test_list_dumps(
    graphql_client: GraphQLClient, upload_file: UploadFile
) -> None:
    """Only this code system's dumps, with when each was written."""
    # Only the names are read
    await upload_file(MAY_1_EVENING, "")
    await upload_file(APRIL_30, "")
    await upload_file("region_other_20260502_000000.csv", "")
    await upload_file("sor_report.csv", "")

    dumps = await DumpStore("sor").list_dumps(graphql_client)
    assert dumps.keys() == {MAY_1_EVENING, APRIL_30}


@pytest.mark.integration_test
async def test_load(graphql_client: GraphQLClient, upload_file: UploadFile) -> None:
    await upload_file(APRIL_30, VALID)
    store = DumpStore("sor")
    dumps = await store.list_dumps(graphql_client)

    dump = await store.load(graphql_client, dumps[APRIL_30])

    assert dump.file_name == APRIL_30
    assert dump.date == date(2026, 4, 30)
    assert dump.units.keys() == {"R"}


@pytest.mark.integration_test
async def test_load_newest(
    graphql_client: GraphQLClient, upload_file: UploadFile
) -> None:
    await upload_file(MAY_1_MORNING, VALID_WITH_CHILD)
    await upload_file(APRIL_30, VALID)

    dump = await DumpStore("sor").load_newest(graphql_client)

    assert dump.file_name == MAY_1_MORNING
    assert dump.units.keys() == {"R", "C"}


@pytest.mark.integration_test
async def test_load_missing_file(graphql_client: GraphQLClient) -> None:
    # Not in the file store, so when it was written is made up
    dump_file = DumpFile(file_name=APRIL_30, updated_at=datetime.now(UTC))
    with pytest.raises(DumpNotFound):
        await DumpStore("sor").load(graphql_client, dump_file)


@pytest.mark.integration_test
async def test_load_file_that_is_not_a_dump(
    graphql_client: GraphQLClient, upload_file: UploadFile
) -> None:
    await upload_file("sor_report.csv", VALID)
    # Not listed as a dump, so when it was written is made up
    dump_file = DumpFile(file_name="sor_report.csv", updated_at=datetime.now(UTC))
    with pytest.raises(DumpNotFound):
        await DumpStore("sor").load(graphql_client, dump_file)


@pytest.mark.integration_test
async def test_load_invalid_file(
    graphql_client: GraphQLClient, upload_file: UploadFile
) -> None:
    await upload_file(APRIL_30, INVALID)
    store = DumpStore("sor")
    dumps = await store.list_dumps(graphql_client)
    with pytest.raises(InvalidFile):
        await store.load(graphql_client, dumps[APRIL_30])


@pytest.mark.integration_test
async def test_load_is_cached(
    graphql_client: GraphQLClient, upload_file: UploadFile
) -> None:
    """Every event reads the newest dump; don't download it for each."""
    store = DumpStore("sor")
    await upload_file(APRIL_30, VALID)
    dumps = await store.list_dumps(graphql_client)
    dump = await store.load(graphql_client, dumps[APRIL_30])

    # The same dump, not read again
    assert await store.load(graphql_client, dumps[APRIL_30]) is dump


@pytest.mark.integration_test
async def test_overwritten_dump_is_read_again(
    graphql_client: GraphQLClient, upload_file: UploadFile
) -> None:
    """The supplier fixes a dump by uploading it again under the same name."""
    store = DumpStore("sor")
    await upload_file(APRIL_30, VALID)
    dumps = await store.list_dumps(graphql_client)
    await store.load(graphql_client, dumps[APRIL_30])

    await upload_file(APRIL_30, VALID_WITH_CHILD)
    # Listed again, with when it was written now
    dumps = await store.list_dumps(graphql_client)
    dump = await store.load(graphql_client, dumps[APRIL_30])
    assert dump.units.keys() == {"R", "C"}


@pytest.mark.integration_test
async def test_cache_is_per_code_system(
    graphql_client: GraphQLClient, upload_file: UploadFile
) -> None:
    """Loading another code system's dumps does not push this one's out."""
    store = DumpStore("sor")
    other = DumpStore("other")
    await upload_file(APRIL_30, VALID)
    dumps = await store.list_dumps(graphql_client)
    dump = await store.load(graphql_client, dumps[APRIL_30])

    # Two dumps would fill a shared cache
    await upload_file(OTHER_APRIL_30, VALID)
    await upload_file(OTHER_MAY_1, VALID)
    other_dumps = await other.list_dumps(graphql_client)
    await other.load(graphql_client, other_dumps[OTHER_APRIL_30])
    await other.load(graphql_client, other_dumps[OTHER_MAY_1])

    # Still cached, so the same dump
    assert await store.load(graphql_client, dumps[APRIL_30]) is dump


@pytest.mark.integration_test
async def test_invalid_file_is_not_cached(
    graphql_client: GraphQLClient, upload_file: UploadFile
) -> None:
    """The supplier fixes a broken dump by uploading it again."""
    store = DumpStore("sor")
    await upload_file(APRIL_30, INVALID)
    dumps = await store.list_dumps(graphql_client)
    with pytest.raises(InvalidFile):
        await store.load(graphql_client, dumps[APRIL_30])

    await upload_file(APRIL_30, VALID)
    dumps = await store.list_dumps(graphql_client)
    dump = await store.load(graphql_client, dumps[APRIL_30])
    assert dump.units.keys() == {"R"}
