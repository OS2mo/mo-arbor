@pytest.mark.integration_test
async def test_first_ingest_sends_every_unit_in_newest_dump(
    test_client: AsyncClient, upload_file: UploadFile, sor_events: DrainEvents
) -> None:
    """Without a previous ingest, everything in the newest dump is new.

    Older dumps are history and are not ingested.
    """
    await upload_file(APRIL_30, file(row(ROOT)))
    await upload_file(MAY_1, ROOT_A_B)

    assert await ingest(test_client) == ingested(MAY_1, added={ROOT, A, B})
    assert await sor_events() == {ROOT, A, B}


@pytest.mark.integration_test
async def test_ingest_twice_does_nothing(
    test_client: AsyncClient, upload_file: UploadFile, sor_events: DrainEvents
) -> None:
    await upload_file(APRIL_30, ROOT_A_B)
    await ingest(test_client)
    await sor_events()

    assert await ingest(test_client) is None
    assert await sor_events() == set()


@pytest.mark.integration_test
async def test_dumps_in_between_are_skipped(
    test_client: AsyncClient, upload_file: UploadFile, sor_events: DrainEvents
) -> None:
    """Only the difference to the newest dump matters.

    B is renamed on May 1st and removed on May 2nd, so the rename is never
    sent on its own.
    """
    await upload_file(APRIL_30, ROOT_A_B)
    await ingest(test_client)
    await sor_events()

    await upload_file(
        MAY_1, file(row(ROOT), row(A, parent=ROOT), row(B, parent=ROOT, name="Renamed"))
    )
    await upload_file(MAY_2, file(row(ROOT), row(A, parent=ROOT), row(C, parent=ROOT)))

    assert await ingest(test_client) == ingested(MAY_2, added={C}, removed={B})
    assert await sor_events() == {B, C}


