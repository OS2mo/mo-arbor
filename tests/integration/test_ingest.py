# Made-up codes in the shape of real ones, with valid check digits
ROOT = "1001000016005"
A = "100001000016006"
B = "1000001000016004"
C = "20011000016005"

# File patterns of CODE_SYSTEMS in CI
MARCH_31 = "region_sor_20260331_120000.csv"
APRIL_30 = "region_sor_20260430_120000.csv"
MAY_1 = "region_sor_20260501_120000.csv"
MAY_2 = "region_sor_20260502_120000.csv"
OKOSTED_APRIL_30 = "region_okosted_20260430_120000.csv"

ROOT_A_B = file(row(ROOT), row(A, parent=ROOT), row(B, parent=ROOT))

DrainEvents = Callable[[], Awaitable[set[str]]]


async def listen(graphql_client: GraphQLClient, namespace: str) -> DrainEvents:
    """Subjects of the namespace's unit events sent since the last call."""
    # The app declares the code systems' namespaces on startup (test_client)
    listener = await graphql_client.declare_event_listener(
        input=ListenerCreateInput(
            namespace=namespace, routing_key="org_unit", user_key="test"
        )
    )

    async def drain() -> set[str]:
        subjects = set()
        # `event_fetch` uses `for update skip locked` in MO, so it may return
        # null while events remain. `list_events` is a plain read, so we loop
        # on that instead.
        while (await graphql_client.list_events(listener.uuid)).objects:
            event = await graphql_client.fetch_event(listener.uuid)
            if event is not None:
                await graphql_client.acknowledge_event(event.token)
                subjects.add(event.subject)
        return subjects

    return drain


@pytest.fixture
async def sor_events(
    test_client: AsyncClient, graphql_client: GraphQLClient
) -> DrainEvents:
    return await listen(graphql_client, "sor")


@pytest.fixture
async def okosted_events(
    test_client: AsyncClient, graphql_client: GraphQLClient
) -> DrainEvents:
    return await listen(graphql_client, "okosted")


async def ingest_all(test_client: AsyncClient, **params: Any) -> dict[str, Any]:
    r = await test_client.post("/ingest", params=params)
    r.raise_for_status()
    return r.json()


async def ingest(test_client: AsyncClient, **params: Any) -> dict[str, Any] | None:
    """Ingest SOR only."""
    ingested = await ingest_all(test_client, code_system="sor", **params)
    return ingested["sor"]


def ingested(
    file_name: str,
    added: Iterable[str] = (),
    changed: Iterable[str] = (),
    removed: Iterable[str] = (),
) -> dict[str, Any]:
    return {
        "file_name": file_name,
        "added": sorted(added),
        "changed": sorted(changed),
        "removed": sorted(removed),
    }


def errors(cap_logs: list[MutableMapping[str, Any]]) -> list[tuple[str, str | None]]:
    # The event handler also runs in the background and logs its own errors
    return [
        (log["event"], log.get("file_name"))
        for log in cap_logs
        if log["log_level"] == "error"
    ]


@pytest.mark.integration_test
async def test_nothing_to_ingest(
    test_client: AsyncClient, sor_events: DrainEvents
) -> None:
    assert await ingest_all(test_client) == {"sor": None, "okosted": None}
    assert await sor_events() == set()


@pytest.mark.integration_test
async def test_code_systems_are_ingested_separately(
    test_client: AsyncClient,
    upload_file: UploadFile,
    sor_events: DrainEvents,
    okosted_events: DrainEvents,
) -> None:
    """Each code system has its own dumps and events.

    An invalid dump in one does not stop the others.
    """
    await upload_file(APRIL_30, "not a dump")
    await upload_file(OKOSTED_APRIL_30, file(row("X"), row("Y", parent="X")))

    assert await ingest_all(test_client) == {
        "sor": None,
        "okosted": ingested(OKOSTED_APRIL_30, added={"X", "Y"}),
    }
    assert await sor_events() == set()
    assert await okosted_events() == {"X", "Y"}


