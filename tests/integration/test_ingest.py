from tests.helpers import UploadFile
from tests.helpers import file
from tests.helpers import row

# Made-up codes in the shape of real ones, with valid check digits
ROOT = "1001000016005"
A = "100001000016006"
B = "1000001000016004"
C = "20011000016005"

# File patterns of CODE_SYSTEMS in CI
MARCH_31 = "region_sor_20260331_120000.csv"
APRIL_30 = "region_sor_20260430_120000.csv"
MAY_1 = "region_sor_20260501_120000.csv"
MAY_2 = "region_sor_20260502_120000.csv"
OKOSTED_APRIL_30 = "region_okosted_20260430_120000.csv"

ROOT_A_B = file(row(ROOT), row(A, parent=ROOT), row(B, parent=ROOT))


async def listen(graphql_client: GraphQLClient, namespace: str) -> UUID:
    """MO gives a listener only the events sent after it is declared."""
    listener = await graphql_client._testing__declare_event_listener(
        input=ListenerCreateInput(
            namespace=namespace, routing_key="org_unit", user_key="test"
        )
    )
    return listener.uuid


async def handle(graphql_client: GraphQLClient, listener: UUID) -> set[str]:
    """Acknowledge the listener's events, as the handler does.

    Returns their subjects.
    """
    subjects: set[str] = set()
    while True:
        event = await graphql_client._testing__fetch_event(listener)
        if event is None:
            return subjects
        subjects.add(event.subject)
        await graphql_client._testing__acknowledge_event(event.token)


async def ingest_all(test_client: AsyncClient) -> dict[str, Ingested | None]:
    r = await test_client.post("/ingest")
    r.raise_for_status()
    return parse_obj_as(dict[str, Ingested | None], r.json())


async def ingest(test_client: AsyncClient) -> Ingested | None:
    """Ingest SOR only."""
    r = await test_client.post("/ingest", params={"code_system": "sor"})
    r.raise_for_status()
    ingested = parse_obj_as(dict[str, Ingested | None], r.json())
    return ingested["sor"]


def ingested(
    file_name: str,
    added: Iterable[str] = (),
    changed: Iterable[str] = (),
    removed: Iterable[str] = (),
) -> Ingested:
    changes = Diff(added=set(added), changed=set(changed), removed=set(removed))
    return Ingested(file_name=file_name, changes=changes)


@pytest.mark.integration_test
async def test_nothing_to_ingest(
    test_client: AsyncClient, graphql_client: GraphQLClient
) -> None:
    listener = await listen(graphql_client, "sor")

    assert await ingest_all(test_client) == {"sor": None, "okosted": None}
    assert await handle(graphql_client, listener) == set()


@pytest.mark.integration_test
async def test_code_systems_are_ingested_separately(
    test_client: AsyncClient, graphql_client: GraphQLClient, upload_file: UploadFile
) -> None:
    """Each code system has its own dumps and events."""
    sor = await listen(graphql_client, "sor")
    okosted = await listen(graphql_client, "okosted")
    await upload_file(OKOSTED_APRIL_30, file(row("X"), row("Y", parent="X")))

    assert await ingest_all(test_client) == {
        "sor": None,
        "okosted": ingested(OKOSTED_APRIL_30, added={"X", "Y"}),
    }
    assert await handle(graphql_client, sor) == set()
    assert await handle(graphql_client, okosted) == {"X", "Y"}


@pytest.mark.integration_test
async def test_unknown_code_system(test_client: AsyncClient) -> None:
    r = await test_client.post("/ingest", params={"code_system": "unknown"})
    assert r.status_code == 404


@pytest.mark.integration_test
async def test_first_ingest_sends_every_unit_in_newest_dump(
    test_client: AsyncClient, graphql_client: GraphQLClient, upload_file: UploadFile
) -> None:
    """Without a previous ingest, everything in the newest dump is new.

    Older dumps are history and are not ingested.
    """
    listener = await listen(graphql_client, "sor")
    await upload_file(APRIL_30, file(row(ROOT)))
    await upload_file(MAY_1, ROOT_A_B)

    assert await ingest(test_client) == ingested(MAY_1, added={ROOT, A, B})
    assert await handle(graphql_client, listener) == {ROOT, A, B}


@pytest.mark.integration_test
async def test_ingest_twice_does_nothing(
    test_client: AsyncClient, graphql_client: GraphQLClient, upload_file: UploadFile
) -> None:
    """The newest dump is the one last ingested, so there is nothing to send."""
    listener = await listen(graphql_client, "sor")
    await upload_file(APRIL_30, ROOT_A_B)
    assert await ingest(test_client) == ingested(APRIL_30, added={ROOT, A, B})
    assert await handle(graphql_client, listener) == {ROOT, A, B}

    assert await ingest(test_client) is None
    assert await handle(graphql_client, listener) == set()


@pytest.mark.integration_test
async def test_dumps_in_between_are_skipped(
    test_client: AsyncClient, graphql_client: GraphQLClient, upload_file: UploadFile
) -> None:
    """Only the newest dump is compared to the last ingested one.

    B is renamed in the May 1st dump and removed in the May 2nd dump, so B is
    removed, not changed.
    """
    listener = await listen(graphql_client, "sor")
    await upload_file(APRIL_30, ROOT_A_B)
    assert await ingest(test_client) == ingested(APRIL_30, added={ROOT, A, B})
    assert await handle(graphql_client, listener) == {ROOT, A, B}

    await upload_file(
        MAY_1, file(row(ROOT), row(A, parent=ROOT), row(B, parent=ROOT, name="Renamed"))
    )
    await upload_file(MAY_2, file(row(ROOT), row(A, parent=ROOT), row(C, parent=ROOT)))

    assert await ingest(test_client) == ingested(MAY_2, added={C}, removed={B})
    assert await handle(graphql_client, listener) == {B, C}


@pytest.mark.integration_test
async def test_dump_older_than_last_ingest_is_ignored(
    test_client: AsyncClient, graphql_client: GraphQLClient, upload_file: UploadFile
) -> None:
    """The newest dump is still the one last ingested."""
    listener = await listen(graphql_client, "sor")
    await upload_file(APRIL_30, ROOT_A_B)
    assert await ingest(test_client) == ingested(APRIL_30, added={ROOT, A, B})
    assert await handle(graphql_client, listener) == {ROOT, A, B}

    await upload_file(MARCH_31, file(row(ROOT)))

    assert await ingest(test_client) is None
    assert await handle(graphql_client, listener) == set()
