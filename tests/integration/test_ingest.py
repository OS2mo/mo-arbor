@pytest.mark.integration_test
async def test_invalid_dump_is_not_ingested(
    test_client: AsyncClient, upload_file: UploadFile, sor_events: DrainEvents
) -> None:
    await upload_file(APRIL_30, ROOT_A_B)
    await ingest(test_client)
    await sor_events()

    await upload_file(MAY_1, "not a dump")

    with capture_logs() as cap_logs:
        assert await ingest(test_client) is None
    assert await sor_events() == set()
    assert ("Invalid dump", MAY_1) in errors(cap_logs)

    # The supplier uploads a fixed dump
    await upload_file(MAY_1, file(row(ROOT), row(A, parent=ROOT)))

    assert await ingest(test_client) == ingested(MAY_1, removed={B})
    assert await sor_events() == {B}


@pytest.mark.integration_test
async def test_last_ingested_dump_not_found(
    app: FastAPI,
    test_client: AsyncClient,
    upload_file: UploadFile,
    sor_events: DrainEvents,
) -> None:
    """Without the last ingested dump, the units removed since cannot be found."""
    # MO cannot delete files, so record an ingest of a dump never uploaded
    sessionmaker = app.state.context["sessionmaker"]
    async with sessionmaker() as session, session.begin():
        session.add(LastApplied(code_system="sor", file_name=APRIL_30))
    await upload_file(MAY_1, ROOT_A_B)

    with capture_logs() as cap_logs:
        assert await ingest(test_client) is None
    assert await sor_events() == set()
    assert ("Last ingested dump not found", APRIL_30) in errors(cap_logs)


@pytest.mark.integration_test
async def test_invalid_last_ingested_dump(
    app: FastAPI,
    test_client: AsyncClient,
    upload_file: UploadFile,
    sor_events: DrainEvents,
) -> None:
    """Without the last ingested dump, the units removed since cannot be found."""
    await upload_file(APRIL_30, ROOT_A_B)
    await ingest(test_client)
    await sor_events()

    await upload_file(APRIL_30, "not a dump")
    # As after a restart, so the overwritten dump is read
    app.state.context["user_context"]["dumps"]["sor"].load.cache_clear()
    await upload_file(MAY_1, file(row(ROOT), row(A, parent=ROOT)))

    with capture_logs() as cap_logs:
        assert await ingest(test_client) is None
    assert await sor_events() == set()
    assert ("Invalid last ingested dump", APRIL_30) in errors(cap_logs)


@pytest.mark.integration_test
@pytest.mark.envvar(
    {
        "CODE_SYSTEMS": json.dumps(
            [
                {
                    "name": "sor",
                    "file_pattern": "region_sor_%Y%m%d_%H%M%S.csv",
                    "uuid_namespace": "sor.dk",
                    "max_terminations": 1,
                }
            ]
        )
    }
)
async def test_too_many_terminations_are_not_ingested(
    test_client: AsyncClient, upload_file: UploadFile, sor_events: DrainEvents
) -> None:
    await upload_file(APRIL_30, ROOT_A_B)
    await ingest(test_client)
    await sor_events()

    await upload_file(MAY_1, file(row(ROOT)))

    with capture_logs() as cap_logs:
        assert await ingest(test_client) is None
    assert await sor_events() == set()
    assert ("Too many terminations in dump", MAY_1) in errors(cap_logs)

    # An operator checks the dump and forces it through
    assert await ingest(test_client, force=True) == ingested(MAY_1, removed={A, B})
    assert await sor_events() == {A, B}


@pytest.mark.integration_test
async def test_dry_run(
    test_client: AsyncClient, upload_file: UploadFile, sor_events: DrainEvents
) -> None:
    await upload_file(APRIL_30, ROOT_A_B)
    await ingest(test_client)
    await sor_events()

    await upload_file(MAY_1, file(row(ROOT), row(A, parent=ROOT)))
    expected = ingested(MAY_1, removed={B})

    assert await ingest(test_client, dry_run=True) == expected
    assert await sor_events() == set()

    # Nothing was recorded, so the real ingest does the same
    assert await ingest(test_client) == expected
    assert await sor_events() == {B}
