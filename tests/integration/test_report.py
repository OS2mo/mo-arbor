@pytest.mark.integration_test
@pytest.mark.envvar(REPORT_ENV)
async def test_no_dumps(test_client: AsyncClient) -> None:
    """Fails, as a code system without dumps has no roots to report from."""
    with capture_logs() as cap_logs:
        r = await test_client.post("/report")

    assert r.status_code == 500
    not_reported = {log["error"] for log in cap_logs if log["event"] == "Not reported"}
    assert not_reported == {"no dumps of sor", "no dumps of okosted"}


@pytest.mark.integration_test
@pytest.mark.envvar(REPORT_ENV)
async def test_roots_not_in_mo(
    test_client: AsyncClient, upload_file: UploadFile
) -> None:
    """Fails, as the systems in the report are named after the roots."""
    await upload_file(APRIL_30, file(row(ROOT), row(A, parent=ROOT)))

    with capture_logs() as cap_logs:
        r = await test_client.post("/report", params={"code_system": "sor"})

    assert r.status_code == 500
    not_reported = {log["error"] for log in cap_logs if log["event"] == "Not reported"}
    assert not_reported == {f"root {ROOT_ADM} is not an active unit in MO"}


