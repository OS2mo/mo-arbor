@pytest.mark.integration_test
@pytest.mark.envvar(REPORT_ENV)
async def test_sor_not_in_mo(test_client: AsyncClient) -> None:
    """Fails, as SOR's units are found under its root."""
    with capture_logs() as cap_logs:
        r = await test_client.post("/report")

    assert r.status_code == 500
    not_reported = {
        (log["report"], log["error"])
        for log in cap_logs
        if log["event"] == "Not reported"
    }
    assert not_reported == {("loen", "no root of sor in MO")}


@pytest.mark.integration_test
@pytest.mark.envvar(REPORT_ENV)
async def test_roots_not_in_mo(
    test_client: AsyncClient,
    graphql_client: GraphQLClient,
    sor: CodeSystem,
    region: UUID,
) -> None:
    """Fails, as the systems in the report are named after the roots."""
    await graphql_client.create_org_unit(
        OrganisationUnitCreateInput(
            uuid=sor.org_unit_uuid(ROOT),
            user_key=ROOT,
            name="SOR",
            org_unit_type=region,
            validity=RAValidityInput(from_=mo_datetime(date(2020, 1, 1))),
        )
    )

    with capture_logs() as cap_logs:
        r = await test_client.post("/report", params={"name": "loen"})

    assert r.status_code == 500
    not_reported = {log["error"] for log in cap_logs if log["event"] == "Not reported"}
    assert not_reported == {f"root {ROOT_ADM} is not an active unit in MO"}


