ROOT = "1001000016005"
A = "100001000016006"
APRIL_30 = "region_sor_20260430_120000.csv"
ADM1 = UUID("b0000000-0000-4000-8000-000000000001")
S1 = UUID("b0000000-0000-4000-8000-000000000002")

HEADER = (
    '"Source_System";"Source_Code";"Source_Name";"Adm_System";"Adm_Code";'
    '"Adm_Name";"Target_System";"Target_Code";"Target_Name"\r\n'
)


# The report of the trees fixture
REPORT = (
    HEADER
    # Sorted by code as text, so A's comes first. The systems are named after
    # the roots.
    + '"SOR";"100001000016006";"Afdeling A";'
    '"Adm-træet";"ADM1";"Adm 1";"Target-træet";"S1";"Target 1"\r\n'
    + '"SOR";"1001000016005";"SOR";"";"";"";"";"";""\r\n'
)


async def report(test_client: AsyncClient, dry_run: bool = False) -> Reported | None:
    """Report SOR only."""
    r = await test_client.post(
        "/report", params={"code_system": "sor", "dry_run": dry_run}
    )
    r.raise_for_status()
    return parse_obj_as(dict[str, Reported | None], r.json())["sor"]


async def report_files(graphql_client: GraphQLClient) -> set[str]:
    files = await graphql_client.list_files(FileStore.EXPORTS)
    return {f.file_name for f in files.objects if "_relations_" in f.file_name}


async def read(graphql_client: GraphQLClient, file_name: str) -> str:
    files = await graphql_client.read_file(FileStore.EXPORTS, file_name)
    return base64.b64decode(one(files.objects).base64_contents).decode("utf-8")


@pytest.fixture
async def trees(
    graphql_client: GraphQLClient,
    upload_file: UploadFile,
    sor: CodeSystem,
    region: UUID,
) -> None:
    """SOR's ROOT and A, the Adm tree with ADM1, and the target tree with S1.

    A is related to ADM1, which is related to S1. ROOT is related to nothing.
    """
    # The roots of SOR's tree come from its newest dump
    await upload_file(APRIL_30, file(row(ROOT), row(A, parent=ROOT)))
    units = [
        (sor.org_unit_uuid(ROOT), ROOT, "SOR", None),
        (sor.org_unit_uuid(A), A, "Afdeling A", sor.org_unit_uuid(ROOT)),
        (ROOT_ADM, "adm", "Adm-træet", None),
        (ADM1, "ADM1", "Adm 1", ROOT_ADM),
        (ROOT_TARGET, "target", "Target-træet", None),
        (S1, "S1", "Target 1", ROOT_TARGET),
    ]
    for uuid, user_key, name, parent in units:
        await graphql_client.create_org_unit(
            OrganisationUnitCreateInput(
                uuid=uuid,
                user_key=user_key,
                name=name,
                parent=parent,
                org_unit_type=region,
                validity=RAValidityInput(from_=mo_datetime(date(2020, 1, 1))),
            )
        )
    await graphql_client._testing__relate_units(
        RelatedUnitsUpdateInput(
            origin=ADM1,
            destination=[sor.org_unit_uuid(A), S1],
            validity=RAValidityInput(from_=mo_datetime(date(2020, 1, 1))),
        )
    )


@pytest.mark.integration_test
@pytest.mark.envvar(REPORT_ENV)
@pytest.mark.usefixtures("trees")
async def test_report(test_client: AsyncClient, graphql_client: GraphQLClient) -> None:
    """A row per chain, uploaded once until something changes."""
    reported = await report(test_client)

    assert reported is not None
    assert reported.file_name.startswith("sor_relations_")
    assert reported.rows == 2
    assert await read(graphql_client, reported.file_name) == REPORT
    # Nothing changed, so nothing is uploaded
    assert await report(test_client) is None
    assert await report_files(graphql_client) == {reported.file_name}


@pytest.mark.integration_test
@pytest.mark.envvar(REPORT_ENV)
@pytest.mark.usefixtures("trees")
async def test_compared_with_last_written(
    test_client: AsyncClient, graphql_client: GraphQLClient, upload_file: UploadFile
) -> None:
    """Not the newest name, as the time in the name repeats an hour in October."""
    # The same report under the newest name, then another under an older name
    newest_name = "sor_relations_20991231_235959.csv"
    older_name = "sor_relations_20000101_000000.csv"
    await upload_file(newest_name, REPORT)
    await upload_file(older_name, "Another report")

    reported = await report(test_client)

    assert reported is not None
    assert await report_files(graphql_client) == {
        newest_name,
        older_name,
        reported.file_name,
    }


