async def report(test_client: AsyncClient, dry_run: bool = False) -> Reported | None:
    r = await test_client.post("/report", params={"name": "loen", "dry_run": dry_run})
    r.raise_for_status()
    return parse_obj_as(dict[str, Reported | None], r.json())["loen"]


async def report_files(graphql_client: GraphQLClient) -> set[str]:
    files = await graphql_client.list_files(FileStore.EXPORTS)
    return {f.file_name for f in files.objects if "_report_" in f.file_name}


async def read(graphql_client: GraphQLClient, file_name: str) -> str:
    files = await graphql_client.read_file(FileStore.EXPORTS, file_name)
    return base64.b64decode(one(files.objects).base64_contents).decode("utf-8")


async def relate(
    graphql_client: GraphQLClient, origin: UUID, destination: list[UUID], start: date
) -> None:
    """Relate the origin to exactly the destinations, from the start."""
    await graphql_client._testing__relate_units(
        RelatedUnitsUpdateInput(
            origin=origin,
            destination=destination,
            validity=RAValidityInput(from_=mo_datetime(start)),
        )
    )


@pytest.fixture
async def trees(
    graphql_client: GraphQLClient,
    sor: CodeSystem,
    region: UUID,
) -> None:
    """SOR's units, the Adm tree with ADM1, and the løn tree with S1.

    A, ENDED and FUTURE are related to ADM1, which is related to S1. ROOT is
    related to nothing.
    """
    always = date(2020, 1, 1)
    units = [
        (sor.org_unit_uuid(ROOT), ROOT, "SOR", None, always),
        (sor.org_unit_uuid(A), A, "Afdeling A", sor.org_unit_uuid(ROOT), always),
        (
            sor.org_unit_uuid(ENDED),
            ENDED,
            "Lukket afdeling",
            sor.org_unit_uuid(ROOT),
            always,
        ),
        (
            sor.org_unit_uuid(FUTURE),
            FUTURE,
            "Ny afdeling",
            sor.org_unit_uuid(ROOT),
            date(2099, 1, 1),
        ),
        (ROOT_ADM, "adm", "Adm-træet", None, always),
        (ADM1, "ADM1", "Adm 1", ROOT_ADM, always),
        (ROOT_LOEN, "loen", "Løn-træet", None, always),
        (S1, "S1", "Løn 1", ROOT_LOEN, always),
    ]
    for uuid, user_key, name, parent, start in units:
        await graphql_client.create_org_unit(
            OrganisationUnitCreateInput(
                uuid=uuid,
                user_key=user_key,
                name=name,
                parent=parent,
                org_unit_type=region,
                validity=RAValidityInput(from_=mo_datetime(start)),
            )
        )
    a, ended, future = (sor.org_unit_uuid(k) for k in [A, ENDED, FUTURE])
    await relate(graphql_client, ADM1, [a, ended, S1], always)
    # ENDED closes at the end of 2023. MO only terminates it once its relations
    # are removed by then.
    await relate(graphql_client, ADM1, [a, S1], date(2024, 1, 1))
    await graphql_client.terminate_org_unit(
        OrganisationUnitTerminateInput(uuid=ended, to=mo_datetime(date(2024, 1, 1)))
    )
    await relate(graphql_client, ADM1, [a, S1, future], date(2099, 1, 1))


@pytest.mark.integration_test
@pytest.mark.envvar(REPORT_ENV)
@pytest.mark.usefixtures("trees")
async def test_report(test_client: AsyncClient, graphql_client: GraphQLClient) -> None:
    """A row per chain, uploaded once until something changes."""
    reported = await report(test_client)

    assert reported is not None
    assert reported.file_name.startswith("sor_loen_report_")
    assert reported.rows == 4
    assert await read(graphql_client, reported.file_name) == LOEN_REPORT
    # Nothing changed, so nothing is uploaded
    assert await report(test_client) is None
    assert await report_files(graphql_client) == {reported.file_name}


@pytest.mark.integration_test
@pytest.mark.envvar(REPORT_ENV)
@pytest.mark.usefixtures("trees")
async def test_compared_with_last_written(
    test_client: AsyncClient, graphql_client: GraphQLClient, upload_file: UploadFile
) -> None:
    """Not the newest name, as the time in the name repeats an hour in October."""
    # The same report under the newest name, then another under an older name
    newest_name = "sor_loen_report_20991231_235959.csv"
    older_name = "sor_loen_report_20000101_000000.csv"
    await upload_file(newest_name, LOEN_REPORT)
    await upload_file(older_name, "Another report")

    reported = await report(test_client)

    assert reported is not None
    assert await report_files(graphql_client) == {
        newest_name,
        older_name,
        reported.file_name,
    }


