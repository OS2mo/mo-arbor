from tests.helpers import row


@pytest.mark.integration_test
async def test_create_root_unit(
    graphql_client: GraphQLClient, region: UUID, okosted: CodeSystem
) -> None:
    await create_root_unit(graphql_client, okosted)
    # MO has it, so it is not made again
    await create_root_unit(graphql_client, okosted)

    assert okosted.root_unit is not None
    r = await graphql_client.get_org_unit(okosted.root_unit.uuid)
    current = one(r.objects).current
    assert current is not None
    assert current.user_key == "okosted"
    assert current.name == "Økosted"
    assert current.parent_response is None
    assert current.unit_type_response is not None
    assert current.unit_type_response.uuid == region


@pytest.mark.integration_test
async def test_units_in_mo(graphql_client: GraphQLClient, region: UUID) -> None:
    """The code system's units under its root unit, with their depth.

    Not the root unit itself, a unit made by hand under it, or a unit outside it.
    """
    okosted = CodeSystem(name="okosted")
    assert okosted.root_unit is not None
    root_unit = okosted.root_unit.uuid
    validity = RAValidityInput(from_=mo_datetime(date(2020, 1, 1)))
    await create_root_unit(graphql_client, okosted)
    await graphql_client.create_org_unit(
        OrganisationUnitCreateInput(
            uuid=okosted.org_unit_uuid("X"),
            user_key="X",
            name="X",
            parent=root_unit,
            org_unit_type=region,
            validity=validity,
        )
    )
    await graphql_client.create_org_unit(
        OrganisationUnitCreateInput(
            uuid=okosted.org_unit_uuid("Y"),
            user_key="Y",
            name="Y",
            parent=okosted.org_unit_uuid("X"),
            org_unit_type=region,
            validity=validity,
        )
    )
    # Made by hand under X, so its UUID is not derived from its user_key
    await graphql_client.create_org_unit(
        OrganisationUnitCreateInput(
            uuid=uuid4(),
            user_key="Z",
            name="Z",
            parent=okosted.org_unit_uuid("X"),
            org_unit_type=region,
            validity=validity,
        )
    )
    # Outside the root unit
    await graphql_client.create_org_unit(
        OrganisationUnitCreateInput(
            uuid=okosted.org_unit_uuid("W"),
            user_key="W",
            name="W",
            org_unit_type=region,
            validity=validity,
        )
    )
    dump = Dump(
        file_name="region_okosted_20260430_120000.csv",
        date=date(2026, 4, 30),
        units=Rows.parse(file(row("X"))),
    )

    assert await units_in_mo(graphql_client, okosted, dump) == {"X": 1, "Y": 2}
